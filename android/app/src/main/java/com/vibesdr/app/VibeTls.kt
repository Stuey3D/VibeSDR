/**
 * ★★★ MODERN ROOTS FOR OLD PHONES — added to the system's trust, never instead of it.
 *
 * ★★★ THE FAULT (B10). Kiko's VibeServer Lite on a Moto G (Android 5.1) showed his UK visitor's ASN
 *     and NO FLAG, while Brazilian visitors had theirs. His logcat: "Trust anchor for certification
 *     path not found" fetching the RIPE and APNIC registry files (and the benchmark clip). Those
 *     hosts, and GitHub's release downloads, chain to ISRG Root X1 (Let's Encrypt) — which Android
 *     only trusts from 7.1.1. ARIN, LACNIC and AFRINIC chain to DigiCert and worked, so the country
 *     table was built from three registries out of five: the Americas and Africa had flags, Europe,
 *     the Middle East and Asia-Pacific had none. The ASN came from iptoasn.com (Google Trust
 *     Services, cross-signed by GlobalSign's 1998 root, which every Android has) and was fine.
 *
 * ★★★ NEVER WEAKER THAN THE PLATFORM. A chain the SYSTEM trusts is accepted exactly as before; a chain
 *     it rejects is accepted only if it validates — full PKIX path, signatures, dates — to one of the
 *     public roots below. Nothing here trusts all, skips a check, or touches hostname verification
 *     (OkHttp's own verifier still runs). These are roots every current browser and every recent
 *     Android already ships; an old phone simply predates them.
 *
 * ★★ WHICH ROOTS, AND WHY EACH (chains checked with `openssl s_client -showcerts`, 2026-10-01):
 *    • ISRG Root X1 — ftp.ripe.net, ftp.apnic.net, release-assets/objects.githubusercontent.com
 *      (the benchmark clip and the map packs), apt.vibesdr.net. Served as YR1/YR2 → "Root YR"
 *      cross-signed by X1. Android 7.1.1+ only.
 *    • ISRG Root X2 — Let's Encrypt's ECDSA chains (E-series intermediates).
 *    • DigiCert Global Root G2 — ftp.arin.net, ftp.lacnic.net, ftp.afrinic.net. Already on 5.1 by
 *      Kiko's evidence; carried so an older or trimmed store is covered too.
 *    • GTS Root R1 / R4 — vibesdr.net and iptoasn.com. Today cross-signed by GlobalSign Root CA, which
 *      EXPIRES 28 Jan 2028; after that only these keep an old phone talking to our own directory.
 *    • USERTrust ECC / RSA — github.com itself (Sectigo), the first hop of every release download.
 *    ✗ NOT carried: ISRG "Root YR"/"Root YE" as self-signed roots — no copy in a store we could check
 *      them against. Today every Let's Encrypt host sends YR cross-signed by X1, which X1 covers; if
 *      that cross-sign is ever dropped, add them here.
 *  ★ Copied from the macOS system root store and checked by SHA-256 (in the comment by each).
 *
 * ★★ WHY A WRAPPER AND NOT network_security_config. NSC does not exist below API 24, and Lite runs on
 *    API 21 — which is exactly where this is needed. One code path for every API level.
 *    ⚠ If either app ever adds a DOMAIN-specific network_security_config, the platform will refuse the
 *    two-argument checkServerTrusted() used below ("Domain specific configurations require that
 *    hostname aware checkServerTrusted is used") — the bundled roots would then still validate their
 *    own hosts, but anything else would fail. Neither app has one today (cleartext is set by attribute).
 *
 * ★ PURE JDK, no android.* imports — so test-tls-roots.sh can compile and run THIS file on a desktop
 *   JVM against the real chains, with an old phone's store simulated.
 *
 * Use: OkHttpClient.Builder().sslSocketFactory(VibeTls.socketFactory, VibeTls.trustManager)
 */
object VibeTls {

    /** The system's trust plus the roots below. Built once, on first use (off the DSP threads: every
     *  caller is a download, which runs at low priority). */
    @JvmStatic val trustManager: X509TrustManager by lazy { withAddedRoots(systemTrustManager()) }

    @JvmStatic val socketFactory: SSLSocketFactory by lazy {
        SSLContext.getInstance("TLS").apply { init(null, arrayOf<TrustManager>(trustManager), null) }.socketFactory
    }

    /** `base` (the system's, or a test's stand-in for an old phone's) plus the bundled roots. */
    @JvmStatic fun withAddedRoots(base: X509TrustManager?): X509TrustManager =
        AddedRootsTrustManager(base, trustManagerFor(bundledRoots()))

    @JvmStatic fun bundledRoots(): List<X509Certificate> {
        val cf = CertificateFactory.getInstance("X.509")
        return PEMS.map { cf.generateCertificate(ByteArrayInputStream(it.trim().toByteArray())) as X509Certificate }
    }

    /** A PKIX trust manager whose ONLY anchors are `roots` — the platform's own validation code. */
    @JvmStatic fun trustManagerFor(roots: List<X509Certificate>): X509TrustManager {
        val ks = KeyStore.getInstance(KeyStore.getDefaultType()).apply { load(null, null) }
        roots.forEachIndexed { i, c -> ks.setCertificateEntry("vibe-root-$i", c) }
        val tmf = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm()).apply { init(ks) }
        return tmf.trustManagers.filterIsInstance<X509TrustManager>().first()
    }

    private fun systemTrustManager(): X509TrustManager? = try {
        val tmf = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm())
        tmf.init(null as KeyStore?)
        tmf.trustManagers.filterIsInstance<X509TrustManager>().firstOrNull()
    } catch (_: Exception) { null }

    /** ★ System first, unchanged; the bundled roots only for a chain the system rejected. When both
     *  reject, the SYSTEM's error is the one thrown — it is the one that describes the device. */
    private class AddedRootsTrustManager(
        private val system: X509TrustManager?,
        private val added: X509TrustManager,
    ) : X509TrustManager {
        override fun checkServerTrusted(chain: Array<X509Certificate>, authType: String) {
            if (system == null) { added.checkServerTrusted(chain, authType); return }
            try {
                system.checkServerTrusted(chain, authType)
            } catch (e: CertificateException) {
                try { added.checkServerTrusted(chain, authType) } catch (_: CertificateException) { throw e }
            }
        }
        override fun checkClientTrusted(chain: Array<X509Certificate>, authType: String) {
            (system ?: added).checkClientTrusted(chain, authType)
        }
        override fun getAcceptedIssuers(): Array<X509Certificate> =
            (system?.acceptedIssuers ?: emptyArray()) + added.acceptedIssuers
    }

