// Generates handheld-ui/src/aprs_marks.h — the APRS map icons' pictures as 8-bit coverage masks, rasterised from the
// SAME drawings the app and the web client use (src/services/tracks.ts APRS_GLYPH / APRS_CODE_GLYPH — read here, never
// retyped). The R36S draws the coloured disc and its ring itself (map_page.h mapAprsIcon) and tints a mask dark on it,
// exactly as tracks.ts aprsIcon() lays out its 22 × 22 SVG — scaled to ICON px for the 640 × 480 panel.
// Needs rsvg-convert (librsvg). Run: node handheld-ui/test/gen_aprs_marks.mjs
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { inflateSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const ICON = 26;   // px (the app's 22, × 1.2 as the receiver's radio is)

const ts = readFileSync(path.join(ROOT, 'src/services/tracks.ts'), 'utf8');
const block = (name) => {
  const m = new RegExp(`const ${name}: Record<string, string> = \\{([\\s\\S]*?)\\n\\};`).exec(ts);
  if (!m) throw new Error(`tracks.ts: ${name} not found`);
  const out = {};
  for (const e of m[1].matchAll(/(?:'((?:[^'\\]|\\.)*)'|"([^"]*)"|([A-Za-z_]\w*))\s*:\s*'([^']*)'/g)) out[(e[1] ?? e[2] ?? e[3]).replace(/\\'/g, "'")] = e[4];
  return out;
};
const GLYPH = block('APRS_GLYPH'), CODE = block('APRS_CODE_GLYPH');
// tracks.ts aprsIcon: these three are drawn as lines (fill none, stroke 1.5), the rest filled (stroke 0.4)
const LINE = new Set(['heli', 'bike', 'antenna']);
if (!/APRS_CODE_GLYPH\[code\] === 'heli' \|\| APRS_CODE_GLYPH\[code\] === 'bike' \|\| APRS_CODE_GLYPH\[code\] === 'antenna'/.test(ts))
  throw new Error('tracks.ts aprsIcon: the line-drawn set changed — update LINE here');

function render(svg) {
  const png = execFileSync('rsvg-convert', ['-w', String(ICON), '-h', String(ICON), '-f', 'png'], { input: svg });
  let p = 8, w = 0, h = 0; const idat = [];
  while (p < png.length) {
    const len = png.readUInt32BE(p), type = png.toString('latin1', p + 4, p + 8), d = png.subarray(p + 8, p + 8 + len);
    if (type === 'IHDR') { w = d.readUInt32BE(0); h = d.readUInt32BE(4); if (d[8] !== 8 || d[9] !== 6) throw new Error('png: want 8-bit RGBA'); }
    else if (type === 'IDAT') idat.push(d);
    p += 12 + len;
  }
  const raw = inflateSync(Buffer.concat(idat)), bpp = 4, stride = w * bpp, out = Buffer.alloc(h * stride);
  for (let y = 0; y < h; y++) {
    const f = raw[y * (stride + 1)], src = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    for (let x = 0; x < stride; x++) {
      const a = x >= bpp ? out[y * stride + x - bpp] : 0, b = y > 0 ? out[(y - 1) * stride + x] : 0;
      const c = x >= bpp && y > 0 ? out[(y - 1) * stride + x - bpp] : 0;
      let v = src[x];
      if (f === 1) v += a; else if (f === 2) v += b; else if (f === 3) v += (a + b) >> 1;
      else if (f === 4) { const pp = a + b - c, pa = Math.abs(pp - a), pb = Math.abs(pp - b), pc = Math.abs(pp - c); v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c; }
      out[y * stride + x] = v & 255;
    }
  }
  const alpha = new Uint8Array(w * h);
  for (let i = 0; i < w * h; i++) alpha[i] = out[i * 4 + 3];
  return alpha;
}
const names = Object.keys(GLYPH);
const masks = names.map((n) => {
  const line = LINE.has(n);
  return render(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 22 22"><path d="${GLYPH[n]}" transform="translate(3 3)" `
    + `fill="${line ? 'none' : '#fff'}" stroke="#fff" stroke-width="${line ? 1.5 : 0.4}" stroke-linejoin="round" stroke-linecap="round"/></svg>`);
});
const arr = (a) => { const r = []; for (let i = 0; i < a.length; i += 26) r.push('    ' + Array.from(a.subarray(i, i + 26)).join(',')); return r.join(',\n'); };
const cpp = (s) => s === "'" ? "'\\''" : s === '\\' ? "'\\\\'" : `'${s}'`;
writeFileSync(path.join(ROOT, 'handheld-ui/src/aprs_marks.h'), `// GENERATED by handheld-ui/test/gen_aprs_marks.mjs — do not edit. The APRS map icons' pictures (coverage 0..255,
// ${ICON} × ${ICON}), from src/services/tracks.ts APRS_GLYPH — the app's and the web client's own drawings.
#pragma once
#include <cstdint>
namespace hh {
namespace aprsmark {
constexpr int kSize = ${ICON}, kCount = ${names.length};
inline const char* const kNames[kCount] = {${names.map((n) => `"${n}"`).join(', ')}};
inline const uint8_t kMask[kCount][kSize * kSize] = {
${masks.map((m) => '  {\n' + arr(m) + '\n  }').join(',\n')}
};
/** tracks.ts APRS_CODE_GLYPH: the symbol code → its picture (-1 = none: the code itself is drawn, as the app does). */
inline int glyphFor(char code) {
    switch (code) {
${Object.entries(CODE).map(([c, g]) => `        case ${cpp(c)}: return ${names.indexOf(g)};   // ${g}`).join('\n')}
        default: return -1;
    }
}
}  // namespace aprsmark
}  // namespace hh
`);
console.log(`aprs_marks.h: ${names.length} pictures, ${Object.keys(CODE).length} codes, ${ICON}px`);
