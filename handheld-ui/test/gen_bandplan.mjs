// gen_bandplan.mjs — writes src/bandplan_gen.h from the app's own band plan (src/constants/bandPlan.ts), so the handheld's
// band-aware step / mode on a jump is the app's, byte for byte. Run: node test/gen_bandplan.mjs
import fs from "node:fs";
const { BAND_PLAN } = await import(new URL("../../src/constants/bandPlan.ts", import.meta.url).href);
const q = (s) => JSON.stringify(s ?? "");
let out = `// GENERATED by handheld-ui/test/gen_bandplan.mjs from src/constants/bandPlan.ts — do not edit.\n#pragma once\nnamespace hh {\n`;
out += `struct BandDef { double lo, hi; const char* name; int type /* 0 ham 1 broadcast 2 utility */; const char* mode; int step; int regions /* bitmask 1<<r, 0 = all */; const char* label; };\n`;
out += `inline const BandDef kBandPlan[] = {\n`;
for (const b of BAND_PLAN) {
  const t = { ham: 0, broadcast: 1, utility: 2 }[b.type];
  const rm = (b.regions || []).reduce((m, r) => m | (1 << r), 0);
  out += `    {${b.lo}, ${b.hi}, ${q(b.name)}, ${t}, ${q(b.mode)}, ${b.step ?? 0}, ${rm}, ${q(b.bandLabel)}},\n`;
}
out += `};\ninline const int kBandPlanN = ${BAND_PLAN.length};\n}  // namespace hh\n`;
fs.writeFileSync(new URL("../src/bandplan_gen.h", import.meta.url), out);
console.log("bands:", BAND_PLAN.length);
