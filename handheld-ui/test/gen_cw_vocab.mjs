// Generates handheld-ui/src/cw_vocab.h — the ham-CW vocabulary the R36S's EXPLAIN key reads CW through, from THE one
// source the app, the web and the server's CW language model share: src/utils/cwVocab.ts (CW_TERMS + aliases via BY_CODE,
// FOREIGN_WORDS, ENGLISH_TOO, PHRASES — imported, never retyped). The algorithm itself is cw_plain.h, a line-for-line
// port of plainEnglish; test/cw_plain_test.cpp checks it against plainEnglish on a corpus (run_cw_plain_test.sh).
// Run: node handheld-ui/test/gen_cw_vocab.mjs   (Node ≥ 22.6 strips the TypeScript types itself)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const V = await import(path.join(ROOT, 'src/utils/cwVocab.ts'));

const q = (s) => JSON.stringify(s);   // a JSON string is a valid C++ string literal for this text (ASCII + —)
const lines = [];
lines.push('// cw_vocab.h — GENERATED by handheld-ui/test/gen_cw_vocab.mjs from src/utils/cwVocab.ts. Do not edit.');
lines.push('#pragma once');
lines.push('');
lines.push('/** Every code the plain reading knows (aliases included, as cwVocab BY_CODE): kind q / a(bbr) / p(rosign) / t(erm) /');
lines.push(' *  n(umber), the plain reading (\'\' = guide only), the question form (nullptr = plain + "?"), ambiguous. */');
lines.push('struct CwVocabTerm { const char* code; char kind; const char* plain; const char* ask; bool ambiguous; };');
lines.push('inline constexpr CwVocabTerm kCwVocab[] = {');
const kindChar = { q: 'q', abbr: 'a', prosign: 'p', term: 't', number: 'n' };
for (const [code, t] of V.BY_CODE) {
  lines.push(`    {${q(code)}, '${kindChar[t.kind]}', ${q(t.plain)}, ${t.ask === undefined ? 'nullptr' : q(t.ask)}, ${t.ambiguous ? 'true' : 'false'}},`);
}
lines.push('};');
lines.push('inline constexpr const char* kCwForeignWords[] = {');
lines.push('    ' + [...V.FOREIGN_WORDS].map(q).join(', ') + ',');
lines.push('};');
lines.push('inline constexpr const char* kCwEnglishToo[] = {');
lines.push('    ' + [...V.ENGLISH_TOO].map(q).join(', ') + ',');
lines.push('};');
lines.push('/** Multi-word phrases, matched first, in this order (up to 4 words). */');
lines.push('struct CwVocabPhrase { const char* words[4]; int n; const char* plain; };');
lines.push('inline constexpr CwVocabPhrase kCwPhrases[] = {');
for (const p of V.PHRASES) {
  if (p.words.length > 4) throw new Error('a phrase over 4 words — widen CwVocabPhrase');
  const w = [...p.words.map(q), ...Array(4 - p.words.length).fill('nullptr')];
  lines.push(`    {{${w.join(', ')}}, ${p.words.length}, ${q(p.plain)}},`);
}
lines.push('};');
writeFileSync(path.join(ROOT, 'handheld-ui/src/cw_vocab.h'), lines.join('\n') + '\n');
console.log(`cw_vocab.h: ${V.BY_CODE.size} codes, ${V.FOREIGN_WORDS.size} foreign words, ${V.PHRASES.length} phrases`);

// ── the corpus for cw_plain_test.cpp: every guide example, every code alone / asked / repeated, glued prosigns, other
//    languages, numbers — and a seeded random mix — each with plainEnglish's reading (TAB separated, one per line) ──
if (process.argv.includes('--golden')) {
  const out = process.argv[process.argv.indexOf('--golden') + 1];
  const cases = new Set();
  for (const t of V.CW_TERMS) if (t.example) cases.add(t.example.toUpperCase());
  for (const c of V.BY_CODE.keys()) { cases.add(c); cases.add(c + '?'); cases.add(`${c} ${c} ${c}`); cases.add(`G4ABC ${c} M0PKZ`); }
  [
    'CQ CQ CQ DE G4ABC G4ABC K', 'TNX FER CALL UR RST IS 599 599', 'UR RST 579 NAME JOHN QTH NR LONDON',
    'HW CPY? BK', 'HW?+M0PKZ', 'G4TPJ( ', '=OPIS DAVE=', 'NR 5 NR', 'NR', 'TU 73 <SK>', '73 88 72 599 3560',
    'GRAZIE CIAO SONO MARIO QTH ROMA 73', 'MUY BUENAS NOCHES ES QTH MADRID', 'TNX FER QSO?', 'PSE QSL?', 'CQ DX CQ DX',
    '  ', '', 'E E E T T', 'R R', 'QRZ? QRZ?', 'ES ES ES', 'GD DX ES 73', 'RST IS 5NN', 'FB OM TNX FER RPRT',
    'line one\nTNX FER CALL\n\nCQ TEST', 'MY QTH IS KENT ES NAME IS STUART', 'OP IS ALAN = RIG IC7300 = ANT DIPOLE',
  ].forEach((c) => cases.add(c));
  let seed = 12345;
  const rnd = (n) => { seed = (Math.imul(seed, 1103515245) + 12345) & 0x7fffffff; return seed % n; };
  const pool = [...V.BY_CODE.keys(), ...V.CW_QSO_WORDS, ...V.CW_NAMES.slice(0, 20), ...V.CW_OTHER_LANGUAGE_WORDS.slice(0, 30),
    'G4ABC', 'M0PKZ', 'EA8/G4ABC/P', '599', '5NN', '3560', '?', 'E', 'T', 'TT', 'X'];
  for (let k = 0; k < 2000; k++) {
    const n = 1 + rnd(12);
    const w = [];
    for (let i = 0; i < n; i++) {
      let tok = pool[rnd(pool.length)];
      if (rnd(9) === 0) tok += '?';
      if (rnd(14) === 0) tok = ['=', '+', '('][rnd(3)] + tok;
      if (rnd(14) === 0) tok += ['=', '+', '('][rnd(3)];
      w.push(tok);
    }
    cases.add(w.join(rnd(6) === 0 ? '  ' : ' '));
  }
  const rows = [];
  for (const c of cases) {
    const enc = (s) => s.replace(/\\/g, '\\\\').replace(/\n/g, '\\n').replace(/\t/g, '\\t');
    rows.push(enc(c) + '\t' + enc(V.plainEnglish(c)));
  }
  writeFileSync(out, rows.join('\n') + '\n');
  console.log(`golden: ${rows.length} cases → ${out}`);
}
