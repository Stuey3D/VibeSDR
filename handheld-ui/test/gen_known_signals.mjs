// gen_known_signals.mjs — writes src/known_signals_gen.h from the app's own curated known-signal table
// (src/utils/knownSignals.ts KNOWN_SIGNALS), so the handheld's spectrum labels name the same signals, at the same
// frequencies, with the same decoder and priority as the app and the web client. Run: node test/gen_known_signals.mjs
// (from handheld-ui/, or with any cwd — paths are relative to this file).
import fs from "node:fs";
const { KNOWN_SIGNALS } = await import(new URL("../../src/utils/knownSignals.ts", import.meta.url).href);
const q = (s) => JSON.stringify(s ?? "");
let out = `// GENERATED by handheld-ui/test/gen_known_signals.mjs from src/utils/knownSignals.ts KNOWN_SIGNALS — do not edit.\n`;
out += `// The curated table the spectrum's SIGNAL LABELS start from (known_labels.h). lo/hi = -1: no span bar.\n`;
out += `#pragma once\nnamespace hh {\n`;
out += `struct KnownSigDef { double hz, lo, hi; const char* label; const char* dec; double dialHz; const char* mode; int prio; };\n`;
out += `inline const KnownSigDef kKnownSignals[] = {\n`;
for (const s of KNOWN_SIGNALS) {
  out += `    {${s.hz}, ${s.lo ?? -1}, ${s.hi ?? -1}, ${q(s.label)}, ${q(s.dec)}, ${s.dialHz}, ${q(s.mode)}, ${s.prio}},\n`;
}
out += `};\ninline const int kKnownSignalsN = ${KNOWN_SIGNALS.length};\n}  // namespace hh\n`;
fs.writeFileSync(new URL("../src/known_signals_gen.h", import.meta.url), out);
console.log("known signals:", KNOWN_SIGNALS.length);
