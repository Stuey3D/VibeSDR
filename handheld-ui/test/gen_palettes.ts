/** Writes handheld-ui/src/wf/wf_palettes_gen.h from the app's own palette code (src/assets/colormapUtils.ts getColorLUT,
 *  over every COLORMAP_NAMES entry) — so the handheld's LUTs ARE the app's, byte for byte.
 *  Run: node --no-warnings --import ./ts_resolve.mjs gen_palettes.ts */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { COLORMAP_NAMES, getColorLUT } from '../../src/assets/colormapUtils.ts';
const here = dirname(fileURLToPath(import.meta.url));
let out = '// GENERATED by handheld-ui/test/gen_palettes.ts from src/assets/colormapUtils.ts getColorLUT — do not edit.\n' +
  '#pragma once\n#include <cstdint>\nnamespace wf {\n' +
  `constexpr int PALETTE_COUNT = ${COLORMAP_NAMES.length};\n` +
  `static const char* const PALETTE_NAMES[PALETTE_COUNT] = { ${COLORMAP_NAMES.map((n) => JSON.stringify(n)).join(', ')} };\n` +
  'static const uint8_t PALETTE_RGB[PALETTE_COUNT][256 * 3] = {\n';
for (const name of COLORMAP_NAMES) {
  const l = getColorLUT(name); const a: number[] = [];
  for (let i = 0; i < 256; i++) a.push(l[i * 4], l[i * 4 + 1], l[i * 4 + 2]);
  out += `  /* ${name} */ {${a.join(',')}},\n`;
}
out += '};\n}  // namespace wf\n';
writeFileSync(join(here, '../src/wf/wf_palettes_gen.h'), out);
console.log(`  wrote wf_palettes_gen.h (${COLORMAP_NAMES.length} palettes)`);
