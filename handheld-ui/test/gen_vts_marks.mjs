// Generates handheld-ui/src/vts_marks.h — the VTS bar's RDS and DAB+ marks as 8-bit coverage masks, rasterised from the
// SAME artwork the app draws (assets/branding/rds/RDS_Logo.svg with the mark's viewBox from rdsLogoPaths.ts; the DAB+
// path from dabLogoPaths.ts, split into MAIN and the "+]" exactly as DabMark.tsx's PLUS_RECT / MAIN_CUT do).
// The bar tints a mask with the strip's colour, as the app's `plain` marks are drawn in the mark colour.
// ★ Third-party artwork: read the headers of src/components/RdsMark.tsx and DabMark.tsx before changing how it is drawn.
// Needs rsvg-convert (librsvg). Run: node handheld-ui/test/gen_vts_marks.mjs
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { inflateSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const RDS_H = 15, DAB_H = 20;   // px on the R36S strip (the app: 13 pt and 20 pt)

function render(svg, w, h) {
  const png = execFileSync('rsvg-convert', ['-w', String(w), '-h', String(h), '-f', 'png'], { input: svg });
  return decodePng(png);
}
function decodePng(buf) {
  let p = 8, w = 0, h = 0, ct = 0, bd = 0;
  const idat = [];
  while (p < buf.length) {
    const len = buf.readUInt32BE(p), type = buf.toString('latin1', p + 4, p + 8), d = buf.subarray(p + 8, p + 8 + len);
    if (type === 'IHDR') { w = d.readUInt32BE(0); h = d.readUInt32BE(4); bd = d[8]; ct = d[9]; }
    else if (type === 'IDAT') idat.push(d);
    p += 12 + len;
  }
  if (bd !== 8 || ct !== 6) throw new Error(`png: want 8-bit RGBA, got depth ${bd} type ${ct}`);
  const raw = inflateSync(Buffer.concat(idat)), bpp = 4, stride = w * bpp;
  const out = Buffer.alloc(h * stride);
  for (let y = 0; y < h; y++) {
    const f = raw[y * (stride + 1)], src = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    for (let x = 0; x < stride; x++) {
      const a = x >= bpp ? out[y * stride + x - bpp] : 0, b = y > 0 ? out[(y - 1) * stride + x] : 0;
      const c = x >= bpp && y > 0 ? out[(y - 1) * stride + x - bpp] : 0;
      let v = src[x];
      if (f === 1) v += a; else if (f === 2) v += b; else if (f === 3) v += (a + b) >> 1;
      else if (f === 4) { const pp = a + b - c, pa = Math.abs(pp - a), pb = Math.abs(pp - b), pc = Math.abs(pp - c); v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c; }
      out[y * stride + x] = v & 255;
    }
  }
  const alpha = new Uint8Array(w * h);
  for (let i = 0; i < w * h; i++) alpha[i] = out[i * 4 + 3];
  return { w, h, alpha };
}

// ── RDS: the logo file, its mark's viewBox (rdsLogoPaths.ts RDS_VIEWBOX), every fill white ──
const VB = { x: 35.4, y: 35.5, w: 1063, h: 260.3 };
const rdsW = Math.round(RDS_H * VB.w / VB.h);
let rdsSvg = readFileSync(path.join(ROOT, 'assets/branding/rds/RDS_Logo.svg'), 'utf8');
rdsSvg = rdsSvg.replace(/<svg\b([^>]*?)\swidth="[^"]*"/, '<svg$1').replace(/<svg\b([^>]*?)\sheight="[^"]*"/, '<svg$1')
  .replace(/<svg\b/, `<svg viewBox="${VB.x} ${VB.y} ${VB.w} ${VB.h}" preserveAspectRatio="none"`);
const rds = render(rdsSvg, rdsW, RDS_H);

// ── DAB+: the official path, MAIN (minus MAIN_CUT) and PLUS (∩ PLUS_RECT) as DabMark.tsx cuts them ──
const dabTs = readFileSync(path.join(ROOT, 'src/components/dabLogoPaths.ts'), 'utf8');
const d = /DAB_LOGO_PATH\s*=\s*'([^']+)'/.exec(dabTs)[1];
const dabW = Math.round(DAB_H * 100 / 59);
const dabSvg = (clip) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 59" preserveAspectRatio="none">
<defs><clipPath id="c">${clip}</clipPath></defs><path d="${d}" fill="#fff" clip-path="url(#c)"/></svg>`;
const main = render(dabSvg('<path clip-rule="evenodd" d="M-10 -10H120V80H-10Z M66.4 16.5h40v50h-40Z"/>'), dabW, DAB_H);
const plus = render(dabSvg('<rect x="67.4" y="16.5" width="40" height="50"/>'), dabW, DAB_H);

const arr = (a) => {
  const rows = [];
  for (let i = 0; i < a.length; i += 24) rows.push('    ' + Array.from(a.subarray(i, i + 24)).join(','));
  return rows.join(',\n');
};
writeFileSync(path.join(ROOT, 'handheld-ui/src/vts_marks.h'), `// GENERATED by handheld-ui/test/gen_vts_marks.mjs — do not edit. The VTS bar's marks as coverage masks (0..255).
// RDS: assets/branding/rds/RDS_Logo.svg (the RDS Forum's mark) · DAB+: src/components/dabLogoPaths.ts (WorldDAB's), cut
// into MAIN and PLUS as src/components/DabMark.tsx does. ★ Third-party artwork — see RdsMark.tsx / DabMark.tsx.
#pragma once
#include <cstdint>
namespace hh {
namespace vts {
constexpr int kRdsMarkW = ${rds.w}, kRdsMarkH = ${rds.h};
inline const uint8_t kRdsMark[] = {
${arr(rds.alpha)}
};
constexpr int kDabMarkW = ${main.w}, kDabMarkH = ${main.h};
inline const uint8_t kDabMarkMain[] = {
${arr(main.alpha)}
};
inline const uint8_t kDabMarkPlus[] = {
${arr(plus.alpha)}
};
}  // namespace vts
}  // namespace hh
`);
console.log(`vts_marks.h: RDS ${rds.w}x${rds.h}, DAB ${main.w}x${main.h}`);
