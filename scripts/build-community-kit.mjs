#!/usr/bin/env node
// build-community-kit.mjs — bundle web/community/kit.ts (the server maps' own icons and cards) into ONE plain script for the
// directory's community map page: window.CommunityKit. ★ The output is a GENERATED COPY in the directory (main branch):
//   node scripts/build-community-kit.mjs <path to directory/public/community-kit.js>
// Run it whenever navtexWarn / navtexMap / navtexIcons / tracks / aprsSymbols / sondes / ism / shippingMap change, or the
// ACICONS block of web/mapkit/adsblayer.js (the aircraft glyphs and iconClassOf).
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = process.argv[2];
if (!out) { console.error('usage: build-community-kit.mjs <out.js>'); process.exit(2); }
// ★★ beta96 THE AIRCRAFT GLYPHS (Stuart 11-26: "the correct icon for the aircraft type like the ADS-B map"): the import
//    'vibe:acicons' is the ACICONS block of web/mapkit/adsblayer.js — its glyphs and iconClassOf, lifted verbatim — so the
//    community map draws the very shapes the servers' maps draw, picked by the very same rule. No copy to keep in step.
const ADSB = path.join(root, 'web/mapkit/adsblayer.js');
const acicons = {
  name: 'acicons',
  setup(b) {
    b.onResolve({ filter: /^vibe:acicons$/ }, () => ({ path: ADSB, namespace: 'acicons' }));
    b.onLoad({ filter: /.*/, namespace: 'acicons' }, () => {
      const src = fs.readFileSync(ADSB, 'utf8');
      const at = src.indexOf('/* ══ ACICONS — BEGIN'), end = src.indexOf('/* ══ ACICONS — END');
      if (at < 0 || end < at) throw new Error('build-community-kit: the ACICONS block is missing from web/mapkit/adsblayer.js');
      return { contents: src.slice(at, end) + '\nexport { iconClassOf, acIconSvg, AC_CLASS_NAME, ICONS };\n', loader: 'js', watchFiles: [ADSB] };
    });
  },
};
const r = await build({ entryPoints: [path.join(root, 'web/community/kit.ts')], bundle: true, format: 'iife', globalName: 'CommunityKit',
  minify: true, target: 'es2019', write: false, platform: 'browser', logLevel: 'warning', plugins: [acicons] });
let rev = '';
try { rev = execFileSync('git', ['-C', root, 'rev-parse', '--short', 'HEAD']).toString().trim(); } catch { /* not a checkout */ }
const head = `/* GENERATED by scripts/build-community-kit.mjs (v12-experimental ${rev}) from web/community/kit.ts — DO NOT EDIT.\n`
  + ` * The server maps' own icons, colours and cards (src/services/navtex*, tracks, sondes, ism, shippingMap; src/utils/aprsSymbols,\n`
  + ` * navtex; the aircraft glyphs of web/mapkit/adsblayer.js) for the community map page. GPL-3.0, as the rest of VibeSDR. */\n`;
fs.writeFileSync(out, head + r.outputFiles[0].text);
console.log(`${out}: ${fs.statSync(out).size} bytes`);
