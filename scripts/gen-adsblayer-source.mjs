#!/usr/bin/env node
/* ══════════════════════════════════════════════════════════════════════════════════════════════
 * gen-adsblayer-source.mjs — put the ONE ADS-B layer where each reader loads it from.
 *
 *   node scripts/gen-adsblayer-source.mjs
 *
 * ★★★ web/mapkit/adsblayer.js IS THE ONLY COPY ANYONE EDITS. The readers, as for vibemap.js
 *     (gen-vibemap-source.mjs — the same embedding rules, for the same reasons):
 *       server web client  — web/client/src/generated/adsbLayerSource.ts, a STRING its map window
 *                            evaluates (the window is about:blank; it cannot rely on a /mapgl/ an
 *                            older install might not have)
 *       app WebView        — src/generated/adsbLayerSource.ts, the same string, injected like VIBEMAP_JS
 *       /mapgl/vendor/     — directory/public/mapgl/vendor/adsblayer.js; vibeserver/CMakeLists.txt
 *                            installs every .js there into lib/vibeserver/mapgl/vendor (the directory
 *                            serves it too)
 * ★★ JSON.stringify and nothing else, with </script masked — never a template literal.
 * ★ scripts/test_adsb_layer.mjs fails if any copy is stale.
 * ══════════════════════════════════════════════════════════════════════════════════════════════ */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'web/mapkit/adsblayer.js');
const src = readFileSync(SRC, 'utf8');

// ★ ASSERT, THEN WRITE (gen-vibemap-source.mjs's rule): a wrong file must not ship quietly.
const MUST = ['VibeAdsbLayer', 'cameraFor', 'AutoZoom', 'deadReckon', 'placeLabels', 'GLIDE_MS'];
const missing = MUST.filter((k) => !src.includes(k));
if (missing.length) { console.error(`gen-adsblayer-source: ${SRC} is missing ${missing.join(', ')} — refusing.`); process.exit(1); }
if (src.includes('`')) { console.error('gen-adsblayer-source: adsblayer.js contains a backtick — the app injects it into a template literal.'); process.exit(1); }

const literal = JSON.stringify(src).replace(/<\/script/gi, '<\\/script');
const ts = (who) => `/* GENERATED by scripts/gen-adsblayer-source.mjs from web/mapkit/adsblayer.js — DO NOT EDIT. ${who} */\n`
  + '/* eslint-disable */\nexport const ADSB_LAYER_JS: string = ' + literal + ';\n';

for (const [rel, body] of [['web/client/src/generated/adsbLayerSource.ts', ts('The server web client carries it as a string.')],
                           ['src/generated/adsbLayerSource.ts', ts('The app injects it into its map WebView.')],
                           ['directory/public/mapgl/vendor/adsblayer.js', src]]) {
  const out = join(root, rel);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, body);
  console.log(`wrote ${rel} (${body.length} bytes)`);
}
