#!/usr/bin/env node
/* ══════════════════════════════════════════════════════════════════════════════════════════════
 * PUT THE SHARED ADS-B MAP LAYER WHERE THE APP'S WEBVIEW LOADS IT FROM — the sibling of
 * gen-vibemap-source.mjs, for the same reason and by the same rules.
 *
 * ★★★ web/mapkit/adsblayer.js IS THE ONLY COPY ANYONE EDITS (the web client builds it in from web/
 *     directly). The app has no file server for its map page, so it carries the source as a STRING
 *     and interpolates it into the page at runtime — see MapOverlay.tsx (kind 'adsb').
 * ★★★ JSON.stringify AND NOTHING ELSE, and </script> masked — gen-vibemap-source.mjs says why.
 * ★★ UNTIL THE LAYER IS MERGED this falls back to scripts/adsblayer-stub.js and SAYS SO: the
 *    generated module exports ADSB_LAYER_IS_STUB = true and this script prints a warning. ✗ Never
 *    ship a build whose generated module says STUB.
 * Run after touching web/mapkit/adsblayer.js:  node scripts/gen-adsblayer-source.mjs
 * ══════════════════════════════════════════════════════════════════════════════════════════════ */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const REAL = join(root, 'web/mapkit/adsblayer.js');
const STUB = join(root, 'scripts/adsblayer-stub.js');
const TS_OUT = join(root, 'src/generated/adsbLayerSource.ts');

const isStub = !existsSync(REAL);
const SRC = isStub ? STUB : REAL;
const src = readFileSync(SRC, 'utf8');

/* ★★★ ASSERT, THEN WRITE — an unasserted transform is a silent no-op (gen-vibemap-source.mjs). */
const MUST = ['VibeAdsbLayer', 'create', 'update', 'setReceiver', 'setPrefs', 'destroy'];
const missing = MUST.filter((k) => !src.includes(k));
if (missing.length) {
  console.error(`gen-adsblayer-source: ${SRC} is missing ${missing.join(', ')} — refusing to ship it.`);
  process.exit(1);
}

const literal = JSON.stringify(src).replace(/<\/script/g, '<\\/script');
const ts = `/* GENERATED by scripts/gen-adsblayer-source.mjs from ${isStub ? 'scripts/adsblayer-stub.js (THE STUB)' : 'web/mapkit/adsblayer.js'} — DO NOT EDIT.
 *
 * ★★★ THE SHARED ADS-B MAP LAYER, AS A STRING, for MapOverlay's WebView (kind 'adsb'). INTERPOLATE
 *     IT AT RUNTIME, NEVER PASTE IT — the page is one template literal (see vibemapSource.ts).
 * Regenerate with: node scripts/gen-adsblayer-source.mjs
 */
export const ADSB_LAYER_JS: string = ${literal};

/** ★★ true = the layer is the STUB (plain markers). Must be false in anything that ships. */
export const ADSB_LAYER_IS_STUB = ${isStub ? 'true' : 'false'};
`;
mkdirSync(dirname(TS_OUT), { recursive: true });
writeFileSync(TS_OUT, ts);
const back = readFileSync(TS_OUT, 'utf8');
if (!back.includes('export const ADSB_LAYER_JS') || back.length < src.length) {
  console.error('gen-adsblayer-source: the generated TS does not contain the source — aborting.');
  process.exit(1);
}
console.log(`gen-adsblayer-source: ${src.length} bytes from ${SRC.replace(root + '/', '')} -> ${TS_OUT.replace(root + '/', '')}`);
if (isStub) console.warn('gen-adsblayer-source: ✗ web/mapkit/adsblayer.js is not here yet — the STUB was used.');
