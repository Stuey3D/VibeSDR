// gen-callsign-country.mjs — src/services/callsignCountry.ts's prefix table → android/app/src/main/cpp/vibe_callsign_country.h.
// ★ ONE TABLE, TWO READERS: the app names an FT8 spot's country with the TS table; the server's background FT8 summary
//   (vibe_bgdecode.h) uses this generated copy, so the two cannot disagree. Re-run after editing the TS table:
//     node scripts/gen-callsign-country.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = fs.readFileSync(path.join(root, 'src/services/callsignCountry.ts'), 'utf8');
const body = src.slice(src.indexOf('const PREFIX'), src.indexOf('};', src.indexOf('const PREFIX')));
const rows = [...body.matchAll(/(?:'([^']+)'|([A-Z0-9]+))\s*:\s*'([^']+)'/g)].map((m) => [m[1] || m[2], m[3]]);
if (rows.length < 200) { console.error(`only ${rows.length} prefixes parsed — the TS table's shape changed`); process.exit(1); }
const out = `// vibe_callsign_country.h — GENERATED by scripts/gen-callsign-country.mjs from src/services/callsignCountry.ts. Do not edit.
// Callsign prefix → country, longest prefix wins — the app's own table, so the server's FT8 summary names countries as
// the app's spot list does.
#pragma once
#include <cctype>
#include <string>

namespace vibe {
namespace callsign {

struct PrefixRow { const char* prefix; const char* country; };
inline const PrefixRow* prefixTable(size_t& n) {
    static const PrefixRow t[] = {
${rows.map(([p, c]) => `        { ${JSON.stringify(p)}, ${JSON.stringify(c)} },`).join('\n')}
    };
    n = sizeof(t) / sizeof(t[0]);
    return t;
}
/** countryForCallsign() — '' when unknown. Portable and qualifier tags (/P, /M, /QRP) dropped; the longest part is the call. */
inline std::string country(const std::string& call) {
    std::string c;
    for (char ch : call) c += (char)std::toupper((unsigned char)ch);
    if (c.find('/') != std::string::npos) {
        std::string best, part;
        auto take = [&] { if (!part.empty() && part != "P" && part != "M" && part != "QRP" && part.size() > best.size()) best = part; part.clear(); };
        for (char ch : c) { if (ch == '/') take(); else part += ch; }
        take();
        if (!best.empty()) c = best;
    }
    if (c.empty() || !std::isalnum((unsigned char)c[0])) return "";
    size_t n = 0; const PrefixRow* t = prefixTable(n);
    for (size_t len = c.size() < 4 ? c.size() : 4; len >= 1; --len) {
        const std::string key = c.substr(0, len);
        for (size_t i = 0; i < n; i++) if (key == t[i].prefix) return t[i].country;
    }
    return "";
}

} // namespace callsign
} // namespace vibe
`;
fs.writeFileSync(path.join(root, 'android/app/src/main/cpp/vibe_callsign_country.h'), out);
console.log(`wrote vibe_callsign_country.h (${rows.length} prefixes)`);
