#!/usr/bin/env python3
"""Rough land outlines for the SATELLITE half-globe → src/services/globeCoast.ts (Stuart, 2026-11-20: "rough outlines
would be fine, its just to show satellite pass status visually").

Natural Earth countries (public domain, assets/mapdata/v1/tier0-countries.json) merged into land with DuckDB spatial
(brew install duckdb), simplified at 0.6° (preserve topology), exterior rings over 2 square degrees kept. Output: integer
tenths of a degree, one flat [lon, lat, lon, lat, …] array per ring — ~55 rings, ~1,200 points.
    python3 scripts/gen-globe-coast.py
"""
import json, os, re, subprocess, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets/mapdata/v1/tier0-countries.json')
OUT = os.path.join(ROOT, 'src/services/globeCoast.ts')
TOL, MIN_AREA = 0.6, 2.0

with tempfile.TemporaryDirectory() as tmp:
    csv, txt = os.path.join(tmp, 'c.csv'), os.path.join(tmp, 'land.txt')
    with open(csv, 'w') as f:
        f.write('wkt\n')
        for polys in json.load(open(SRC)).values():
            for ring in polys:
                if len(ring) < 4: continue
                if ring[0] != ring[-1]: ring = ring + [ring[0]]
                f.write('"POLYGON((' + ','.join(f'{x} {y}' for x, y in ring) + '))"\n')
    q = (f"INSTALL spatial; LOAD spatial; COPY (WITH u AS (SELECT ST_Union_Agg(ST_MakeValid(ST_GeomFromText(wkt))) AS g "
         f"FROM read_csv('{csv}', header=true)), d AS (SELECT (UNNEST(ST_Dump(ST_SimplifyPreserveTopology(g, {TOL})))).geom AS p "
         f"FROM u) SELECT ST_AsText(ST_ExteriorRing(p)) FROM d WHERE ST_GeometryType(p)='POLYGON' AND ST_Area(p) > {MIN_AREA}) "
         f"TO '{txt}' (FORMAT csv, HEADER false, QUOTE '');")
    subprocess.run(['duckdb', '-no-agent', '-c', q], check=True)
    rings = re.findall(r'LINESTRING \(([^()]*)\)', open(txt).read())

out = []
for r in rings:
    flat = []
    for p in r.split(','):
        x, y = map(float, p.split())
        flat += [round(x * 10), round(y * 10)]
    out.append('[' + ','.join(map(str, flat)) + ']')
pts = sum(len(r.split(',')) for r in rings)
with open(OUT, 'w') as f:
    f.write('/* GENERATED by scripts/gen-globe-coast.py — do not edit. Rough land outlines for the SATELLITE half-globe:\n'
            f' * Natural Earth countries (public domain) merged, simplified {TOL}°, {len(rings)} rings / {pts} points.\n'
            ' * Each ring is [lon, lat, lon, lat, …] in tenths of a degree. */\n')
    f.write('export const GLOBE_COAST: readonly (readonly number[])[] = [\n' + ',\n'.join(out) + '\n];\n')
print(f'wrote {OUT}: {len(rings)} rings, {pts} points, {os.path.getsize(OUT)} bytes')
