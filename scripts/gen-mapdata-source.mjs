#!/usr/bin/env node
/* ══════════════════════════════════════════════════════════════════════════════════════════════
 * THE APP CARRIES THE BASEMAP. IT IS THE MAP SOURCE FOR EVERY ENGINE IT DRIVES.
 *
 * ★★★ WHY THIS EXISTS. MapOverlay's WebView is handed an HTML STRING with the INSTANCE origin as
 *     baseUrl, so the renderer's root-relative `dataBase: '/mapdata/v1/'` resolves against whatever
 *     the user is listening to. A VibeServer serves that path; an UberSDR and a KiwiSDR do NOT —
 *     https://…/addon/hfdl/aircraft is 200 and /mapdata/v1/index.json is 404, so the HFDL map drew
 *     aircraft over a void. Our own maps were built precisely so the app would stop depending on
 *     somebody else's tiles (openstreetmap.org blocked us for hammering a free service). Being the
 *     map source is therefore the app's job, not the instance's.
 *
 * ★★ WHAT IS EMBEDDED: the BUNDLED PACK, i.e. exactly what vibemap.js says is "present by
 *    definition" — tier0 (1.4 MB, what draws the world at z<=4, which is where the HFDL map OPENS)
 *    and tier1 (13 MB, the 50m set). ✗ NOT tier2 (sharded, 200 MB+, the optional detail pack) and
 *    ✗ NOT the relief PNGs (230 MB of raster). The generated index therefore advertises tier0/tier1
 *    only, with `sharded` emptied and `relief` nulled, so the renderer never asks for a shard or a
 *    relief tile we do not carry — the same contract a VibeServer with only the basic pack presents.
 *
 * ★★★ THE FILES ARE ARROW FUNCTIONS RETURNING STRING LITERALS, NOT AN OBJECT OF STRINGS. Hermes
 *     keeps literals in the bytecode's string table, which is mmapped: the 14 MB only becomes heap
 *     when a getter is CALLED, and the app calls at most the handful of files a given zoom needs.
 *     A plain object literal of strings would be the same bundle and the same laziness, but the
 *     function form makes the intent unmistakable to the next reader. ✗ Do not "simplify" it into a
 *     map of eagerly concatenated strings.
 *
 * ★★★ THE EMBEDDING IS JSON.stringify AND NOTHING ELSE — the same rule as gen-vibemap-source.mjs.
 *     ✗ Never a template literal: a backtick in the data would end the string and the build error
 *     would point at an unrelated line.
 *
 * ★ Regenerate after scripts/sync-mapdata.sh, or after any change to assets/mapdata/v1/:
 *     node scripts/gen-mapdata-source.mjs
 * ══════════════════════════════════════════════════════════════════════════════════════════════ */
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(root, 'assets/mapdata/v1');
const OUT = join(root, 'src/generated/mapdataBundle.ts');

/** ★ The tiers the renderer treats as always-present. Everything else is the optional pack. */
const TIERS = ['tier0-', 'tier1-'];

const names = readdirSync(DATA)
  .filter((f) => f.endsWith('.json') && TIERS.some((t) => f.startsWith(t)))
  .sort();

if (names.length < 20) {
  console.error(`gen-mapdata-source: only ${names.length} tier0/tier1 files in ${DATA} — that is not the pack.`);
  process.exit(1);
}

/* ★★ THE INDEX IS REWRITTEN, NOT COPIED. Shipping the server's index would advertise tier2 shards
 *  and relief tiles that are not in the app, and the renderer would 404 its way to a black hole at
 *  z8 — the exact failure the index exists to prevent. */
const srcIndex = JSON.parse(readFileSync(join(DATA, 'index.json'), 'utf8'));
const files = {};
for (const n of names) if (srcIndex.files && srcIndex.files[n]) files[n] = srcIndex.files[n];
const appIndex = {
  ...srcIndex,
  files,
  sharded: {},
  relief: null,
  packs: { basic: { tiers: ['tier0', 'tier1'], files: names } },
  embeddedIn: 'VibeSDR app',
};

let raw = 0;
const entries = names.map((n) => {
  const body = readFileSync(join(DATA, n), 'utf8');
  raw += body.length;
  // ★ A quick sanity check: every one of these is a JSON array or object, never HTML from a 404.
  const c = body.trimStart()[0];
  if (c !== '[' && c !== '{') {
    console.error(`gen-mapdata-source: ${n} does not start with JSON — refusing to ship it.`);
    process.exit(1);
  }
  return `  ${JSON.stringify(n)}: () => ${JSON.stringify(body)},`;
}).join('\n');

const ts = `/* GENERATED by scripts/gen-mapdata-source.mjs from assets/mapdata/v1/ — DO NOT EDIT.
 *
 * ★★★ THE VECTOR BASEMAP'S DATA, CARRIED BY THE APP, so a map drawn over an UberSDR or a KiwiSDR —
 *     neither of which serves /mapdata/v1/ — still has a world under it. MapOverlay answers the
 *     WebView's mapdata requests from here whenever the instance has none (see its fetch shim).
 * ★★ tier0 + tier1 only: the pack vibemap.js calls "present by definition". tier2 and the relief
 *     rasters stay on the servers that have them, and MAPDATA_INDEX says so.
 * ★ Each file is a getter so the bytes stay in Hermes's mmapped string table until asked for.
 * ★ Regenerate with: node scripts/gen-mapdata-source.mjs
 */

/** The index the renderer probes, rewritten to describe what the APP carries. */
export const MAPDATA_INDEX: string = ${JSON.stringify(JSON.stringify(appIndex))};

/** file name (as requested under /mapdata/v1/) -> its JSON text. */
export const MAPDATA_FILES: Record<string, () => string> = {
  "index.json": () => MAPDATA_INDEX,
${entries}
};

/** ★ Raw JSON bytes embedded, so a caller can sanity-check it got the pack and not a stub. */
export const MAPDATA_BYTES = ${raw};
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, ts);

/* ★ Verify the ARTEFACT, not the command. */
const back = readFileSync(OUT, 'utf8');
if (!back.includes('export const MAPDATA_FILES') || back.length < raw) {
  console.error('gen-mapdata-source: the generated TS does not contain the data — aborting.');
  process.exit(1);
}

console.log(`gen-mapdata-source: ${names.length} files, ${(raw / 1048576).toFixed(1)} MB raw`);
console.log(`  -> ${OUT.replace(root + '/', '')} (${(back.length / 1048576).toFixed(1)} MB of TS)`);
