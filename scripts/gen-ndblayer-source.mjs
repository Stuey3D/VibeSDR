#!/usr/bin/env node
/* gen-ndblayer-source.mjs — put the ONE NDB layer where the web client loads it from (gen-adsblayer-source.mjs's rules).
 *
 *   node scripts/gen-ndblayer-source.mjs
 *
 * ★★★ web/mapkit/ndblayer.js IS THE ONLY COPY ANYONE EDITS. The reader: the server web client —
 *     web/client/src/generated/ndbLayerSource.ts, a STRING it evaluates after the ADS-B layer (whose rings it uses).
 *     The app (V12 NDB, 2026-10-26): src/generated/ndbLayerSource.ts, the same string, injected into its map WebView after
 *     the ADS-B layer (MapOverlay kind 'ndb').
 * ★★ JSON.stringify and nothing else, with </script masked — never a template literal. scripts/test_ndb_layer.mjs fails
 *    if the copy is stale. */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'web/mapkit/ndblayer.js');
const src = readFileSync(SRC, 'utf8');
const MUST = ['VibeNdbLayer', 'ringsFor', 'addRingLayers', 'markerImage'];
const missing = MUST.filter((k) => !src.includes(k));
if (missing.length) { console.error(`gen-ndblayer-source: ${SRC} is missing ${missing.join(', ')} — refusing.`); process.exit(1); }
if (src.includes('`')) { console.error('gen-ndblayer-source: ndblayer.js contains a backtick.'); process.exit(1); }
const literal = JSON.stringify(src).replace(/<\/script/gi, '<\\/script');
const ts = (who) => '/* GENERATED by scripts/gen-ndblayer-source.mjs from web/mapkit/ndblayer.js — DO NOT EDIT. ' + who + ' */\n'
  + '/* eslint-disable */\nexport const NDB_LAYER_JS: string = ' + literal + ';\n';
for (const [rel, body] of [['web/client/src/generated/ndbLayerSource.ts', ts('The server web client carries it as a string.')],
                           ['src/generated/ndbLayerSource.ts', ts('The app injects it into its map WebView.')]]) {
  const out = join(root, rel);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, body);
  console.log(`wrote ${rel} (${body.length} bytes)`);
}
