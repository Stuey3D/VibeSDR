#!/usr/bin/env node
/* ══════════════════════════════════════════════════════════════════════════════════════════════
 * gen-tracklayer-source.mjs — put the ONE ship/station layer (V12 AIS + APRS) where each reader loads it from.
 *
 *   node scripts/gen-tracklayer-source.mjs          (write)
 *   node scripts/gen-tracklayer-source.mjs --check  (fail if a copy is stale — run-tests.sh)
 *
 * ★★★ web/mapkit/tracklayer.js IS THE ONLY COPY ANYONE EDITS — gen-adsblayer-source.mjs's rules, for the same reasons:
 *       server web client — web/client/src/generated/trackLayerSource.ts (a STRING the map evaluates)
 *       app WebView       — src/generated/trackLayerSource.ts (the same string; the app's AIS/APRS map is owed)
 *       /mapgl/vendor/    — directory/public/mapgl/vendor/tracklayer.js
 * ★★ JSON.stringify and nothing else, with </script masked — never a template literal; no backticks in the source.
 * ══════════════════════════════════════════════════════════════════════════════════════════════ */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'web/mapkit/tracklayer.js');
const src = readFileSync(SRC, 'utf8');
const MUST = ['VibeTrackLayer', 'GLIDE_MS', 'vtl-card', 'setReceiver'];
const missing = MUST.filter((k) => !src.includes(k));
if (missing.length) { console.error(`gen-tracklayer-source: ${SRC} is missing ${missing.join(', ')} — refusing.`); process.exit(1); }
if (src.includes('`')) { console.error('gen-tracklayer-source: tracklayer.js contains a backtick — the app injects it into a template literal.'); process.exit(1); }

const literal = JSON.stringify(src).replace(/<\/script/gi, '<\\/script');
const ts = (who) => `/* GENERATED by scripts/gen-tracklayer-source.mjs from web/mapkit/tracklayer.js — DO NOT EDIT. ${who} */\n`
  + '/* eslint-disable */\nexport const TRACK_LAYER_JS: string = ' + literal + ';\n';
const outs = [['web/client/src/generated/trackLayerSource.ts', ts('The server web client carries it as a string.')],
              ['src/generated/trackLayerSource.ts', ts('The app injects it into its map WebView.')],
              ['directory/public/mapgl/vendor/tracklayer.js', src]];
if (process.argv.includes('--check')) {
  const stale = outs.filter(([rel, body]) => !existsSync(join(root, rel)) || readFileSync(join(root, rel), 'utf8') !== body).map(([r]) => r);
  if (stale.length) { console.error(`tracklayer copies are STALE — run node scripts/gen-tracklayer-source.mjs: ${stale.join(', ')}`); process.exit(1); }
  console.log('  ok  the ship/station layer\'s copies match web/mapkit/tracklayer.js');
  process.exit(0);
}
for (const [rel, body] of outs) {
  const out = join(root, rel);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, body);
  console.log(`wrote ${rel} (${body.length} bytes)`);
}
