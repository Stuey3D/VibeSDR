#!/usr/bin/env node
/* ══════════════════════════════════════════════════════════════════════════════════════════════
 * PUT THE ONE RENDERER WHERE EACH ARTEFACT LOADS IT FROM.
 *
 * ★★★ web/mapkit/vibemap.js IS THE ONLY COPY ANYONE EDITS. Three readers want it and they load it
 *     three different ways, which is exactly the shape that produced three drifting basemaps in the
 *     first place:
 *
 *       directory page   -- a <script src>, so it needs a file under directory/public/
 *       app WebView      -- no filesystem at all, so it needs the source as a JS STRING
 *       server web client -- the page is COMPILED IN (see the memory note: a web-client change is a
 *                            server release), and build-web.mjs inlines from web/ directly
 *
 *     This script makes the first two from the third's source. ✗ Never hand-edit either output.
 *
 * ★★ RUN IT AFTER TOUCHING web/mapkit/vibemap.js, AND BEFORE `wrangler deploy` IN directory/ --
 *    same rule, and same failure mode, as scripts/sync-mapdata.sh: a deploy of a stale copy looks
 *    identical to a deploy of a fresh one right up until the map behaves like last week's.
 *
 * ★★★ THE EMBEDDING IS JSON.stringify AND NOTHING ELSE. vibemap.js contains BACKTICKS (its CSS is a
 *     template literal), so wrapping it in a template literal of our own would end the string at the
 *     first one and produce a syntax error pointing at the wrong line -- the exact trap that cost two
 *     goes at MapOverlay.tsx on 2026-09-26. JSON.stringify escapes everything and cannot be fooled by
 *     the content. ✗ Do not "tidy" this into a backtick string.
 * ★★ The consumer must interpolate VIBEMAP_JS at RUNTIME (`${VIBEMAP_JS}` inside the WebView page
 *    template), which is safe: substitution is a value, not source text.
 * ★ </script> is escaped as well, because the app injects the source inside a <script> element and a
 *   literal closing tag in a string still closes it as far as the HTML parser is concerned.
 * ══════════════════════════════════════════════════════════════════════════════════════════════ */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'web/mapkit/vibemap.js');
const TS_OUT = join(root, 'src/generated/vibemapSource.ts');
const WEB_OUT = join(root, 'directory/public/mapkit/vibemap.js');

const src = readFileSync(SRC, 'utf8');

/* ★★★ ASSERT, THEN WRITE. An unasserted transform is a silent no-op: two `replace()` edits matched
 *  nothing on 2026-09-26 and left MAP_REEF and MAP_CAPITAL referenced-but-undefined for an hour,
 *  with no trace anywhere that the edit had not happened. Anything this script believes about its
 *  input, it checks out loud. */
const MUST_CONTAIN = ['VibeMap', 'attach', 'PROFILES', 'LADDER', 'labelPlacer', 'drawBase',
                      'drawRelief', 'drawPlaces', 'worldOffsets', 'maidenhead'];
const missing = MUST_CONTAIN.filter((k) => !src.includes(k));
if (missing.length) {
  console.error(`gen-vibemap-source: ${SRC} is missing ${missing.join(', ')} — refusing to ship it.`);
  process.exit(1);
}
if (src.length < 20000) {
  console.error(`gen-vibemap-source: ${SRC} is only ${src.length} bytes — that is not the renderer.`);
  process.exit(1);
}

// ★ The literal is built by JSON.stringify and then only the closing tag is masked; the split is in
//   the STRING, so the file still evaluates to the same source.
const literal = JSON.stringify(src).replace(/<\/script/g, '<\\/script');

const ts = `/* GENERATED by scripts/gen-vibemap-source.mjs from web/mapkit/vibemap.js — DO NOT EDIT.
 *
 * ★★★ THE VECTOR BASEMAP RENDERER, AS A STRING, for the WebView to evaluate. The app has no file
 *     server, so the only way it can run the same renderer as the directory page and the server's
 *     web client is to carry the source.
 * ★★ INTERPOLATE IT AT RUNTIME, NEVER PASTE IT: MapOverlay.tsx builds its page as one giant
 *     template literal and this source CONTAINS BACKTICKS. \`\${VIBEMAP_JS}\` is fine (a value);
 *     pasting the source in is not (it would close the literal at the first backtick, and the build
 *     error points at a comment line, which is how it cost two goes).
 * ★ Regenerate with: node scripts/gen-vibemap-source.mjs
 */
export const VIBEMAP_JS: string = ${literal};

/** ★ Bytes, so a caller can sanity-check that it got the whole thing rather than a truncated copy. */
export const VIBEMAP_BYTES = ${src.length};
`;

mkdirSync(dirname(TS_OUT), { recursive: true });
writeFileSync(TS_OUT, ts);
mkdirSync(dirname(WEB_OUT), { recursive: true });
writeFileSync(WEB_OUT, src);

/* ★ Verify the ARTEFACT, not the command -- a write that produced nothing useful is the failure we
 *  keep paying for (see "A Mac-only compile is not a build"). Read both back and check a marker that
 *  only survives a correct write. */
const back = readFileSync(TS_OUT, 'utf8');
if (!back.includes('export const VIBEMAP_JS') || back.length < src.length) {
  console.error('gen-vibemap-source: the generated TS does not contain the source — aborting.');
  process.exit(1);
}
if (readFileSync(WEB_OUT, 'utf8') !== src) {
  console.error(`gen-vibemap-source: ${WEB_OUT} does not match the source — aborting.`);
  process.exit(1);
}

console.log(`gen-vibemap-source: ${src.length} bytes`);
console.log(`  -> ${TS_OUT.replace(root + '/', '')}`);
console.log(`  -> ${WEB_OUT.replace(root + '/', '')}`);
