/**
 * mapgl-manifest.mjs — the app's GPU-map manifest (src/generated/mapglAssets.ts), computed from what is
 * actually in assets/mapgl/. ONE function, two readers: sync-mapgl-assets.mjs WRITES it, and
 * check-map-overlay.mjs recomputes it and FAILS when the committed one does not match.
 *
 * ★★★ WHY (2026-10-27, Stuart, the DIGITAL SPOTS MAP on iOS build 497: "dots are missing their numbers, i saw
 *     them once but then never again"). The mode letters are a symbol layer in vibemapgl-compat.js. That file
 *     was edited (534bd77b1) and its copy in assets/mapgl/vendor/ re-synced — but the MANIFEST was not
 *     regenerated, so MAPGL_BYTES still described the old pack. mapglPack.ts copies the pack to
 *     <documents>/mapgl/ only when that version changes, so every iPhone and iPad that already had the pack
 *     kept running the OLD compat (no letter layer) — for good. A fresh install copied the new one, which is
 *     the "saw them once". check-map-overlay compared the asset COPIES with web/mapkit, and they matched; the
 *     version nothing compared was the one that mattered.
 * ★★ THE VERSION IS A CONTENT HASH NOW, not bytes + count — the shape Android's mapgl-assets.gradle already
 *    uses ("<bytes>-<count>-<sha1 prefix>"), so an edit that happens to keep the size can never hide either.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';

/** Every file under assets/mapgl/ the app copies (the style .json rides in the JS bundle, so not it),
 *  sorted, with its on-disk name, its asset path and its bytes. */
export function mapglFiles(dest) {
  const files = [];
  (function walk(dir, rel) {
    for (const n of readdirSync(dir).sort()) {
      const full = path.join(dir, n), r = rel ? `${rel}/${n}` : n;
      if (statSync(full).isDirectory()) walk(full, r);
      else if (!n.endsWith('.json')) files.push({ asset: r, disk: diskName(r), bytes: readFileSync(full) });
    }
  })(dest, '');
  return files;
}

/** ★ The path the file must have on disk: scripts lose their Metro-proof .txt, font folders get their spaces
 *  back (sync-mapgl-assets.mjs explains both). */
function diskName(r) {
  return r.replace(/\.txt$/, '').replace(/^fonts\/([^/]+)/, (m, d) => 'fonts/' + d.replace(/_/g, ' '));
}

/** The text of src/generated/mapglAssets.ts for the files in `dest` (assets/mapgl/). */
export function mapglManifest(dest) {
  const files = mapglFiles(dest);
  const total = files.reduce((a, f) => a + f.bytes.length, 0);
  const sha = createHash('sha1');
  for (const f of files) { sha.update(f.disk); sha.update(f.bytes); }
  const version = `${total}-${files.length}-${sha.digest('hex').slice(0, 12)}`;
  return { total, count: files.length, version, text: `/* GENERATED by scripts/sync-mapgl-assets.mjs from assets/mapgl/ — DO NOT EDIT.
 * ★ The GPU map's bundled files: the basic + relief tile packs, the label fonts and the icons, each
 *   with the path it must have on disk. mapglPack.ts copies them to <documents>/mapgl/ once — the
 *   fonts need a real {fontstack}/{range}.pbf folder layout, which native assets do not have.
 * ★★ MAPGL_VERSION is a CONTENT HASH (scripts/lib/mapgl-manifest.mjs): change any byte of the pack and the
 *    app copies it again. check-map-overlay.mjs fails when this file is stale. */
/* eslint-disable */
export const MAPGL_BYTES = ${total};
export const MAPGL_VERSION = ${JSON.stringify(version)};
export const MAPGL_FILES: ReadonlyArray<readonly [string, number]> = [
${files.map((f) => `  [${JSON.stringify(f.disk)}, require(${JSON.stringify('../../assets/mapgl/' + f.asset)})],`).join('\n')}
];
` };
}
