#!/usr/bin/env python3
"""make-adsb-test-fixtures.py — the small archives test-adsb-data reads (vibeserver/testdata-adsb/).

★ Reproducible and tiny: a few rows in the real upstream LAYOUTS (VRS standing-data tarball as GitHub serves it,
  with its pax global header; Mictronics indexedDB.zip with its comment), carrying the REAL licence texts — the
  builder refuses anything else, which is half of what is being tested. CC0's text is CC0; ODC-By's text is the
  licence itself, which is meant to travel with the data.
★ Plus the hostile zips for the logo installer: zip slip, a bomb, encrypted, and an ordinary pack made both by
  Python (deflated) and stored.
Usage: make-adsb-test-fixtures.py <VRS LICENSE> <Mictronics LICENSE> <out dir>
"""
import io, sys, tarfile, zipfile, json, struct, zlib, time, os

vrs_lic, mic_lic, out = sys.argv[1], sys.argv[2], sys.argv[3]
T = 1761300000

def tar_add(t, name, data):
    ti = tarfile.TarInfo(name); ti.size = len(data); ti.mtime = T; ti.mode = 0o644
    t.addfile(ti, io.BytesIO(data))

bom = b'\xef\xbb\xbf'
buf = io.BytesIO()
with tarfile.open(fileobj=buf, mode='w', format=tarfile.PAX_FORMAT, pax_headers={'comment': 'fixture0123456789'}) as t:
    root = 'standing-data-main/'
    tar_add(t, root + 'LICENSE', open(vrs_lic, 'rb').read())
    tar_add(t, root + 'README.md', b'# Standing Data\n')
    tar_add(t, root + 'airlines/schema-01/airlines.csv', bom + b'Code,Name,ICAO,IATA,PositioningFlightPattern,CharterFlightPattern\n'
            b'BAW,British Airways,BAW,BA,,\nEZY,easyJet,EZY,U2,,\nRYR,Ryanair,RYR,FR,,\nAAA,"Quoted, Airline",AAA,ZZ,,\nBBB,Other ZZ,BBB,ZZ,,\n')
    tar_add(t, root + 'airports/schema-01/E/EG.csv', bom + b'Code,Name,ICAO,IATA,Location,CountryISO2,Latitude,Longitude,AltitudeFeet\n'
            b'EGLL,London Heathrow Airport,EGLL,LHR,London,GB,51.4706,-0.461941,83\nEGKK,London Gatwick Airport,EGKK,LGW,London,GB,51.148102,-0.190278,202\n'
            b'EGSS,London Stansted Airport,EGSS,STN,London,GB,51.885,0.235,348\n')
    tar_add(t, root + 'airports/schema-01/E/EH.csv', bom + b'Code,Name,ICAO,IATA,Location,CountryISO2,Latitude,Longitude,AltitudeFeet\n'
            b'EHAM,Amsterdam Airport Schiphol,EHAM,AMS,Amsterdam,NL,52.308601,4.76389,-11\n')
    tar_add(t, root + 'airports/schema-01/K/KJ.csv', bom + b'Code,Name,ICAO,IATA,Location,CountryISO2,Latitude,Longitude,AltitudeFeet\n'
            b'KJFK,John F Kennedy International Airport,KJFK,JFK,New York,US,40.639801,-73.7789,13\n')
    tar_add(t, root + 'routes/schema-01/B/BAW-all.csv', bom + b'Callsign,Code,Number,AirlineCode,AirportCodes\n'
            b'BAW1,BAW,1,BAW,EGLL-KJFK\nBAW12A,BAW,12A,BAW,EGKK-EHAM-EGSS\n')
    tar_add(t, root + 'routes/schema-01/E/EZY-all.csv', bom + b'Callsign,Code,Number,AirlineCode,AirportCodes\nEZY1,EZY,1,EZY,EHAM-EGSS\n')
    tar_add(t, root + 'model-type/schema-01/B.csv', bom + b'ICAO,Manufacturer,Model,Engines,EngineTypeCode,EnginePlacementCode,SpeciesCode,WakeTurbulenceCode,IsActive\n'
            b'B738,Boeing,737-800,2,J,,L,M,1\nB77W,Boeing,777-300ER,2,J,,L,H,1\n')
    tar_add(t, root + 'code-blocks/schema-01/code-blocks.csv', bom + b'Start,Finish,Count,Bitmask,SignificantBitmask,IsMilitary,CountryISO2\n'
            b'400000,43FFFF,262144,400000,FC0000,0,GB\n43C000,43FFFF,16384,43C000,FFC000,1,GB\n400040,40007F,64,400040,FFFFC0,0,KY\nAE0000,AFFFFF,131072,AE0000,FE0000,1,US\n')
    tar_add(t, root + 'countries/schema-01/countries.csv', bom + b'ISO,Name\nGB,United Kingdom\nKY,Cayman Islands\nUS,United States\nNL,Netherlands\nIE,Ireland\n')
    tar_add(t, root + 'aircraft/schema-01/4/40.csv', bom + b'ICAO,Registration,ModelICAO,Manufacturer,Model,ManufacturerAndModel,IsPrivateOperator,Operator,AirlineCode,SerialNumber,YearBuilt\n'
            b'400ABC,G-PRIV,C172,Cessna,172,Cessna 172,1,Jane Bloggs,,1,1990\n400ABD,G-COMP,B738,Boeing,737,Boeing 737,0,Acme Charter Ltd,,2,2001\n')
import gzip
open(os.path.join(out, 'mini-standing-data.tar.gz'), 'wb').write(gzip.compress(buf.getvalue(), mtime=T))

zb = io.BytesIO()
with zipfile.ZipFile(zb, 'w', zipfile.ZIP_DEFLATED) as z:
    z.comment = b'Generated by Mictronics. 18.10.2026 Made available under the Open Data Commons Attribution License.'
    z.writestr('LICENSE', open(mic_lic, 'rb').read())
    z.writestr('dbversion.json', '{"version":527}')
    z.writestr('types.json', json.dumps({'B738': ['BOEING 737-800', 'L2J', 'M'], 'A388': ['AIRBUS A-380-800', 'L4J', 'H'], 'C17': ['BOEING C-17 Globemaster 3', 'L4J', 'H']}))
    z.writestr('operators.json', json.dumps({'BAW': ['British Airways', 'United Kingdom', 'SPEEDBIRD'], 'RYR': ['Ryanair', 'Ireland', 'RYANAIR'], 'LONGKEY': ['x', 'y', 'z']}))
    ac = {'4CA2D6': ['EI-DLJ', 'B738', '00'], '400F01': ['G-XLEA', 'A388', '00'], 'AE1234': ['03-3123', 'C17', '10'],
          '4CA2D7': ['EI-\\"Q"', 'B738', '00', 'desc'], '400ABD': ['', '', '00']}
    for i in range(1200):
        ac['%06X' % (0x500000 + i)] = ['T-%04d' % i, 'B738', '00']
    z.writestr('aircrafts.json', json.dumps(ac))
open(os.path.join(out, 'mini-mictronics.zip'), 'wb').write(zb.getvalue())

PNG = b'\x89PNG\r\n\x1a\n' + b'\x00' * 40
BMP = b'BM' + b'\x00' * 60
SVG = b'<svg xmlns="http://www.w3.org/2000/svg" width="85" height="20"><rect width="85" height="20"/></svg>'
def mk(name, entries, method=zipfile.ZIP_DEFLATED):
    b = io.BytesIO()
    with zipfile.ZipFile(b, 'w', method) as z:
        for n, d in entries: z.writestr(n, d)
    open(os.path.join(out, name), 'wb').write(b.getvalue())
pack = [('OperatorFlags/BAW.png', PNG), ('OperatorFlags/RYR-B738.bmp', BMP), ('OperatorFlags/readme.txt', b'hello'),
        ('Silhouettes/B738.png', PNG), ('Silhouettes/A388.svg', SVG), ('__MACOSX/OperatorFlags/._BAW.png', PNG),
        ('OperatorFlags/fake.png', b'MZ not a png')]
mk('images-deflated.zip', pack)
mk('images-stored.zip', pack, zipfile.ZIP_STORED)
mk('images-flat.zip', [('EZY.png', PNG), ('G-ABCD.gif', b'GIF89a' + b'\x00' * 10)])
mk('images-slip.zip', [('../../evil.png', PNG), ('/abs/evil.png', PNG), ('OperatorFlags/../../evil2.png', PNG),
                       ('C:\\evil3.png', PNG), ('OperatorFlags/ok.png', PNG), ('OperatorFlags/..%2fevil4.png', PNG)])
# a bomb: one member whose local data inflates to 50 MB but whose directory claims 1 KB
b = io.BytesIO()
with zipfile.ZipFile(b, 'w', zipfile.ZIP_DEFLATED) as z:
    z.writestr('OperatorFlags/BOMB.png', PNG + b'\x00' * (50 << 20))
raw = bytearray(b.getvalue())
cd = raw.rfind(b'PK\x01\x02')
struct.pack_into('<I', raw, cd + 24, 1024)          # the central directory's uncompressed size: a lie
open(os.path.join(out, 'images-bomb.zip'), 'wb').write(bytes(raw))
# encrypted flag set on a member
b = io.BytesIO()
with zipfile.ZipFile(b, 'w', zipfile.ZIP_STORED) as z:
    z.writestr('OperatorFlags/ENC.png', PNG)
raw = bytearray(b.getvalue())
cd = raw.rfind(b'PK\x01\x02'); struct.pack_into('<H', raw, cd + 8, 1)
open(os.path.join(out, 'images-encrypted.zip'), 'wb').write(bytes(raw))
# inflate round trip: a deflated member made by zlib at every level, a stored block and a fixed-Huffman stream
data = bytes((i * 7 + (i >> 5)) & 0xFF for i in range(40000)) + b'abcabcabc' * 2000 + bytes(range(256)) * 20
for lvl in (0, 1, 6, 9):
    c = zlib.compressobj(lvl, zlib.DEFLATED, -15)
    open(os.path.join(out, 'raw-deflate-l%d.bin' % lvl), 'wb').write(c.compress(data) + c.flush())
open(os.path.join(out, 'raw-plain.bin'), 'wb').write(data)
# ★ one made by Info-ZIP's `zip` too (a different writer, its own extra fields)
import shutil, subprocess, tempfile
if shutil.which('zip'):
    d = tempfile.mkdtemp()
    os.makedirs(os.path.join(d, 'Silhouettes'))
    open(os.path.join(d, 'Silhouettes', 'C17.png'), 'wb').write(PNG + bytes(range(256)) * 8)
    open(os.path.join(d, 'Silhouettes', 'A20N.bmp'), 'wb').write(BMP)
    dst = os.path.abspath(os.path.join(out, 'images-infozip.zip'))
    if os.path.exists(dst): os.unlink(dst)
    subprocess.check_call(['zip', '-q', '-X', '-r', dst, 'Silhouettes'], cwd=d)
    shutil.rmtree(d)
print('fixtures written to', out)
