/**
 * dotField.ts — what the DOT Display's mode box and frequency unit SHOW, dot by dot (2026-10-06, Stuart: "Dot matrix
 * needs to also have the same treatment [as VCR], except being dot matrix means a lot more flexibility").
 *
 * VCR got FIXED 14-segment fields (constants/segField.ts, components/SegField.tsx). DOT gets the same four things as
 * true DOT-MATRIX fields, drawn by components/DotField.tsx: a fixed grid of 5 × 7 cells with EVERY unlit dot there as
 * a ghost (text colour α .10), the lit dots in the text colour with its glow.
 *
 * ★★★ ONE DOT, DOTO'S DOT. The cells light exactly the dots the Doto font lights — DOTO_GLYPHS below is read out of
 *   assets/fonts/Doto-Black.ttf by scripts/gen_dot_glyphs.mjs (and `--check` holds the two equal). Doto is a dot grid
 *   in its own units: every dot a 90 × 90 SQUARE centred on 50 + 100 k, columns 0 … 4 and rows 0 … 6 above the
 *   baseline, on a 600-unit advance. So at font size F its dot pitch is F × 0.1 (DOT_PITCH_EM), its dot 0.9 of that
 *   (DOT_SIZE), and its cell five dots and one dead column wide (DOT_ADV). A field here at pitch F × 0.1 is the
 *   Doto text it replaces, dot for dot — the same height, the same dots, the same spacing — with the ghosts added.
 *   ★ The cell is MEASURED from the font's outlines, not its spec (memory station_strip_layout_2026_10_03: the
 *     spec's 0.6 em advance was not what iOS drew; the dot grid inside the glyph is what this needs, and that is
 *     the outline's own coordinates).
 *
 * The fields (all FIXED width — nothing moves when the value or the mode changes):
 *
 *   THE MODE FIELD   DOT_MODE_CELLS (10) cells. ★ 2026-10-06: a PLAIN mode is one tight word on the plain cell pitch
 *                    ("AM", "MESHTASTIC" — no colon column); with a decoder: the demod right-aligned in three, a COLON COLUMN of
 *                    its own (two dots wide — Doto Black's colon is a heavy cluster, so 2 × 2 blocks, not single
 *                    dots), then seven cells: "USB:RTTY", "USB:WHISPER", "MESHTASTIC". In WFM the last three
 *                    cells' room is the STEREO RINGS — drawn in dots on the same pitch (DOT_RINGS); in every other
 *                    mode that room is cells. Over-long names step through a cell at a time (segField's rules —
 *                    the cell layout is segModeCells', shared, so the two Displays cannot disagree).
 *   THE READOUT      ten cells, "S9+27 dBFS": the value in cells 0 … 4, a space, then d B F S. A real S (not VCR's
 *                    5), a real plus and minus, full digits (no ±1 half-digit: −120 has a cell of its own).
 *                      S-meter   "S9+27" → S 9 + 2 7 · dB          ("S7" lights no unit)
 *                      dBFS      " -73"  → … dBFS
 *                      SNR       "  24"  → … dB
 *                      dBf       " 120"  → … dBf — a real lower-case f in the F cell (FM-DX's unit)
 *                    Numbers are right-aligned to cell 4 and the over-S9 digits right-aligned under the "+", so a
 *                    reading never hops between columns as it changes.
 *   THE UNIT         three cells beside the frequency digits, RIGHT-aligned: "kHz", "MHz", " Hz" — spelled
 *                    properly, because a dot matrix has lower case (a 14-segment display does not; VCR's capitals
 *                    were that display's compromise, not a rule).
 *
 * ★ Pure: no React, no runtime imports — scripts/test_faceplate_dotfield.ts runs it under plain Node.
 */

/** Doto's dot pitch, em (100 units of a 1000-unit em). */
export const DOT_PITCH_EM = 0.1;
/** A dot's side, in pitches — Doto Black's 90-unit square. */
export const DOT_SIZE = 0.9;
/** A cell: five dots by seven, and one dead column after it (Doto's 600-unit advance). */
export const DOT_COLS = 5;
export const DOT_ROWS = 7;
export const DOT_ADV = 6;

/** The pitch (pt) for Doto text at `fontSize` — what a field takes to sit on the same dots as that text. */
export const dotPitch = (fontSize: number) => fontSize * DOT_PITCH_EM;

