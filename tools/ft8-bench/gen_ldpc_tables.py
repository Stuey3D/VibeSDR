#!/usr/bin/env python3
"""gen_ldpc_tables.py — write ft8_lib/ft8/ldpc_tables.h, the edge tables the fast belief-propagation decoder walks.

    python3 tools/ft8-bench/gen_ldpc_tables.py

★ WHY GENERATED (2026-10-25, the FT8 CPU work): the fast bp_decode (ft8/ldpc.c) lays the 522 edges of the (174,91)
  parity-check graph out check-major, four checks per SIMD vector, and needs to know for every edge which variable it
  touches and where that variable's message lives. Those are fixed facts of the code, so they are constants — built
  from kFTX_LDPC_Nm / kFTX_LDPC_Mn in ft8/constants.c, never typed by hand, and never computed at run time (two
  decoders on two threads would race to build them).
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
FT8 = os.path.join(HERE, '..', '..', 'android', 'app', 'src', 'main', 'cpp', 'ft8_lib', 'ft8')
src = open(os.path.join(FT8, 'constants.c')).read()

def table(name):
    body = re.search(name + r'\[[^\]]*\]\[\d\]\s*=\s*\{(.*?)\n\};', src, re.S).group(1)
    return [[int(v) for v in row.split(',') if v.strip()] for row in re.findall(r'\{([^}]*)\}', body)]

Nm = table('kFTX_LDPC_Nm')   # 83 rows, 1-based variable numbers, 0 = unused
Mn = table('kFTX_LDPC_Mn')   # 174 rows, 1-based check numbers
M, N, NP, MP = 83, 174, 176, 84
assert len(Nm) == M and len(Mn) == N
DUMMY_VAR = N                  # vars 174/175 pad the last vector; their messages are never read
TOC_DUMMY = 7 * MP             # one spare check-message slot the two dummy variables write into

chk_var = [[DUMMY_VAR] * MP for _ in range(7)]
chk_slot = [[0] * MP for _ in range(7)]
var_edge = [[TOC_DUMMY] * NP for _ in range(3)]
masks = []
for m in range(M):
    vs = [v - 1 for v in Nm[m] if v]
    assert len(vs) in (6, 7)
    w = [0, 0, 0]
    for j, n in enumerate(vs):
        k = [c - 1 for c in Mn[n]].index(m)
        chk_var[j][m] = n
        chk_slot[j][m] = k
        var_edge[k][n] = j * MP + m
        w[n >> 6] |= 1 << (n & 63)
    masks.append(w)
for n in range(N):
    assert all(var_edge[k][n] != TOC_DUMMY for k in range(3)), n

def rows(t, per=21):
    out = []
    for r in t:
        lines = [', '.join(str(x) for x in r[i:i + per]) for i in range(0, len(r), per)]
        out.append('    { ' + ',\n      '.join(lines) + ' }')
    return ',\n'.join(out)

h = f"""// GENERATED by tools/ft8-bench/gen_ldpc_tables.py from constants.c — do not edit.
// The (174,91) parity-check graph laid out for the fast bp_decode in ldpc.c (VibeSDR, 2026-10-25; not in upstream ft8_lib).
//   check-major: slot j (0..6) of check m (0..83, 83 = padding) — the variable it touches, and which of that variable's
//   three checks it is; padding slots point at dummy variable {DUMMY_VAR}. var_edge[k][n]: where variable n's k-th
//   check keeps its message in the check-major array (j * {MP} + m); {TOC_DUMMY} = the spare slot for dummy variables.
#ifndef _INCLUDE_LDPC_TABLES_H_
#define _INCLUDE_LDPC_TABLES_H_
#include <stdint.h>
#define LDPC_MP {MP}
#define LDPC_NP {NP}
#define LDPC_TOC_SIZE ({TOC_DUMMY} + 4)
static const uint16_t kLdpcChkVar[7][LDPC_MP] = {{
{rows(chk_var)}
}};
static const uint8_t kLdpcChkSlot[7][LDPC_MP] = {{
{rows(chk_slot)}
}};
static const uint16_t kLdpcVarEdge[3][LDPC_NP] = {{
{rows(var_edge)}
}};
static const uint64_t kLdpcChkMask[{M}][3] = {{
""" + ',\n'.join('    {{ 0x{:016x}ull, 0x{:016x}ull, 0x{:016x}ull }}'.format(*w) for w in masks) + """
};
#endif
"""
open(os.path.join(FT8, 'ldpc_tables.h'), 'w').write(h)
print('wrote', os.path.join(FT8, 'ldpc_tables.h'))
