#!/usr/bin/env node
/**
 * Generate Jr's palette table FROM THE PHONE'S OWN COLOUR DATA.
 *
 * ★ Jr had 8 palettes to the phone's 26, so a colour chosen on the phone was
 *   often simply unreachable on the wrist — which is where the "Sync" option
 *   came from. Sync never worked (applyPalette mapped it to Sonar Green with a
 *   TODO beside it), so the honest fix is for the watch to OFFER THE SAME LIST.
 *
 * ★★ GENERATED, NOT TRANSCRIBED. Hand-copying 26 gradients into Swift is a
 *   guaranteed drift: add a palette to the phone and the watch quietly lacks it,
 *   which is the bug this exists to close. Re-run after changing colormaps.ts:
 *       node tools/gen-watch-palettes.mjs
 *
 * The phone stores palettes three ways (256-packed, even stops, positioned
 * stops); all three are resolved to a 256-entry LUT here using the same maths as
 * colormapUtils.ts, then RESAMPLED to evenly spaced stops for Jr, whose
 * WFPalette interpolates evenly between them. 32 stops is indistinguishable from
 * 256 on a 41 mm waterfall and keeps the Swift readable.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'src/assets/colormaps.ts';
const OUT = 'spike/WristSDR/WristSDR/WFPalettes.generated.swift';
const STOPS = 32;

// The phone's list, in the phone's order — the picker order should match.
const NAMES = [
  'gqrx', 'inferno', 'turbo', 'plasma', 'viridis', 'magma',
  'Classic', 'Classic Green', 'Teejeez', 'Ha7ilm', 'Zoran',
  'Kiwi', 'CuteSDR', 'SdrDx', 'Kiwi Linear',
  'Electric', 'Jet', 'WebSDR', 'Vivid', 'Temper', 'Smoke',
  'Greyscale', 'Black Hot',
  'Night Vision', 'Sonar Green', 'Sonar Orange',
];

// ★ Jr already persists these ids in @AppStorage("wfPalette"). They MUST keep
//   resolving to the same palette or every watch silently changes colour on
//   upgrade. New entries get a slug.
const LEGACY_ID = {
  'Sonar Green': 'sonar',
  'Sonar Orange': 'sonarorange',
  'Night Vision': 'nightvision',
  'Classic': 'classic',
  'Jet': 'jet',
  'viridis': 'viridis',
  'Greyscale': 'grey',
  'Black Hot': 'blackhot',
};
const idFor = (n) => LEGACY_ID[n] ?? n.toLowerCase().replace(/[^a-z0-9]/g, '');

// ── Pull the three tables out of the TS source ───────────────────────────────
const src = readFileSync(SRC, 'utf8');
function evalExport(name) {
  const i = src.indexOf(`export const ${name}`);
  if (i < 0) throw new Error(`${name} not found in ${SRC}`);
  const eq = src.indexOf('=', i);
  // Scan to the matching close brace so a nested object can't end it early.
  let depth = 0, j = eq;
  for (; j < src.length; j++) {
    if (src[j] === '{') depth++;
    else if (src[j] === '}') { depth--; if (depth === 0) { j++; break; } }
  }
  return (0, eval)('(' + src.slice(eq + 1, j) + ')');
}
const packed = evalExport('COLORMAPS_256');
const stops = evalExport('COLORMAPS_STOPS');
const pos = evalExport('COLORMAPS_POS');

const hex2rgb = (h) => {
  const s = h.replace('#', '');
  return [parseInt(s.slice(0, 2), 16), parseInt(s.slice(2, 4), 16), parseInt(s.slice(4, 6), 16)];
};

// Same three builders as colormapUtils.ts, producing 256 RGB triples.
function lut256(p) {
  return Array.from({ length: 256 }, (_, i) => hex2rgb(p.slice(i * 6, i * 6 + 6)));
}
function lutStops(list) {
  const n = list.length - 1;
  return Array.from({ length: 256 }, (_, i) => {
    const t = i / 255, seg = Math.min(Math.floor(t * n), n - 1), f = t * n - seg;
    const a = hex2rgb(list[seg]), b = hex2rgb(list[seg + 1]);
    return a.map((v, k) => Math.round(v + (b[k] - v) * f));
  });
}
function lutPos(list) {
  const out = []; let seg = 0;
  for (let i = 0; i < 256; i++) {
    while (seg < list.length - 2 && i > list[seg + 1][0]) seg++;
    const [p0, c0] = list[seg], [p1, c1] = list[seg + 1];
    const f = p1 > p0 ? Math.max(0, Math.min(1, (i - p0) / (p1 - p0))) : 0;
    const a = hex2rgb(c0), b = hex2rgb(c1);
    out.push(a.map((v, k) => Math.round(v + (b[k] - v) * f)));
  }
  return out;
}

function lutFor(name) {
  if (packed[name]) return lut256(packed[name]);
  if (stops[name]) return lutStops(stops[name]);
  if (pos[name]) return lutPos(pos[name]);
  throw new Error(`no definition for palette "${name}"`);
}

const rows = NAMES.map((name) => {
  const lut = lutFor(name);
  const sampled = Array.from({ length: STOPS }, (_, i) => {
    const [r, g, b] = lut[Math.round((i / (STOPS - 1)) * 255)];
    return '"#' + [r, g, b].map((v) => v.toString(16).padStart(2, '0')).join('') + '"';
  });
  return `  static let ${idFor(name).replace(/^(\d)/, 'p$1')} = WFPalette(id: "${idFor(name)}", name: "${name}",\n`
       + `    hex: [${sampled.join(', ')}])`;
});

const swift = `// GENERATED by tools/gen-watch-palettes.mjs — DO NOT EDIT BY HAND.
//
// Jr's palette list, resampled from the phone's own colour tables
// (src/assets/colormaps.ts) to ${STOPS} evenly spaced stops. Regenerate after
// changing a palette on the phone, or the two drift and a colour chosen there
// becomes unreachable here — which is exactly what the dead "Sync" option was
// papering over.
import Foundation

extension WFPalette {
${rows.join('\n')}

  /// Every palette the phone offers, in the phone's own order.
  static let all: [WFPalette] = [
${NAMES.map((n) => '    .' + idFor(n).replace(/^(\d)/, 'p$1')).join(',\n')},
  ]
}
`;
writeFileSync(OUT, swift);
console.log(`wrote ${OUT}: ${NAMES.length} palettes × ${STOPS} stops`);
