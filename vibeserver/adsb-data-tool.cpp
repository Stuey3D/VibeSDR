// adsb-data-tool — the reproducible half of the ADS-B aircraft data (scripts/build-adsb-data.sh drives it).
//
// ★ The SAME builder the server's weekly update runs (vibe_adsb_data_build.h), so what we ship as the starter and
//   what a server makes for itself are one code path.
//
//   adsb-data-tool build   <standing-data.tar.gz> <indexedDB.zip> <out dir>   → vrs.vad + mic.vad
//   adsb-data-tool starter <standing-data.tar.gz> <out header>                → vibe_adsb_starter.h (CC0 tables only)
//   adsb-data-tool lookup  <dir> <hex> [callsign] [lat lon]                   → the enrichment JSON
//   adsb-data-tool licence-hash <file>                                        → the FNV-1a pin for a licence file
#include "vibe_adsb_data_build.h"
#include <cstdio>
#include <fstream>
#include <sstream>

using namespace vibeadsbdata;

static bool readAll(const char* p, std::string& out) {
    std::ifstream f(p, std::ios::binary);
    if (!f) return false;
    std::stringstream ss; ss << f.rdbuf(); out = ss.str();
    return true;
}

static std::string today() {
    char b[16]; const time_t t = time(nullptr); struct tm tm{}; gmtime_r(&t, &tm);
    std::strftime(b, sizeof b, "%Y-%m-%d", &tm);
    return b;
}

int main(int argc, char** argv) {
    if (argc < 2) { std::fprintf(stderr, "usage: see the head of adsb-data-tool.cpp\n"); return 2; }
    const std::string cmd = argv[1];
    if (cmd == "licence-hash" && argc == 3) {
        std::string s; if (!readAll(argv[2], s)) { std::perror(argv[2]); return 1; }
        std::printf("0x%016llxULL\n", (unsigned long long)fnv1a64(s));
        return 0;
    }
    if (cmd == "build" && argc == 5) {
        std::string tgz, zip, err;
        if (!readAll(argv[2], tgz) || !readAll(argv[3], zip)) { std::fprintf(stderr, "cannot read the inputs\n"); return 1; }
        const std::map<std::string, std::string> meta = {{"retrieved", today()}};
        BuildResult v = buildVrs((const uint8_t*)tgz.data(), tgz.size(), false, meta);
        if (!v.error.empty()) { std::fprintf(stderr, "%s\n", v.error.c_str()); return 1; }
        BuildResult m = buildMic((const uint8_t*)zip.data(), zip.size(), meta);
        if (!m.error.empty()) { std::fprintf(stderr, "%s\n", m.error.c_str()); return 1; }
        const std::string d = argv[4];
        if (!writeAtomic(d + "/vrs.vad", v.bytes, err) || !writeAtomic(d + "/mic.vad", m.bytes, err)) { std::fprintf(stderr, "%s\n", err.c_str()); return 1; }
        std::printf("vrs.vad %zu bytes: %zu routes, %zu airports, %zu airlines, %zu model types, %zu blocks, %zu overlay aircraft (commit %s)\n",
                    v.bytes.size(), v.routes, v.airports, v.airlines, v.types, v.blocks, v.overlay, v.version.c_str());
        std::printf("mic.vad %zu bytes: %zu aircraft, %zu types, %zu operators (dbversion %s)\n",
                    m.bytes.size(), m.aircraft, m.types, m.operators, m.version.c_str());
        return 0;
    }
    if (cmd == "starter" && argc == 4) {
        std::string tgz;
        if (!readAll(argv[2], tgz)) { std::fprintf(stderr, "cannot read %s\n", argv[2]); return 1; }
        const std::map<std::string, std::string> meta = {{"retrieved", today()}, {"starter", "1"}};
        BuildResult v = buildVrs((const uint8_t*)tgz.data(), tgz.size(), true, meta);
        if (!v.error.empty()) { std::fprintf(stderr, "%s\n", v.error.c_str()); return 1; }
        std::string h;
        h += "// vibe_adsb_starter.h — GENERATED by scripts/build-adsb-data.sh (adsb-data-tool starter). Do not edit.\n";
        h += "//\n// ★★ THE NO-NETWORK STARTER: VRS standing data (CC0 1.0 — github.com/vradarserver/standing-data, commit\n//    ";
        h += v.version + ", retrieved " + today() + "): airlines, model types, code blocks (military + territories),\n";
        h += "//    countries. CC0 ONLY, so the package itself conveys no ODC-By data. Routes, airports and the 450 000\n";
        h += "//    aircraft arrive with the server's first weekly update (vibe_adsb_data_update.h).\n";
        h += "// ★ .rodata: paged in only when read, so it costs no RAM on a server that never runs ADS-B.\n";
        h += "#pragma once\n#include <cstddef>\n#include <cstdint>\nnamespace vibeadsbdata {\n";
        h += "alignas(8) inline const uint8_t kStarterVrs[" + std::to_string(v.bytes.size()) + "] = {\n";
        char b[8];
        for (size_t i = 0; i < v.bytes.size(); ++i) {
            std::snprintf(b, sizeof b, "%u,", unsigned((uint8_t)v.bytes[i]));
            h += b;
            if (i % 32 == 31) h += '\n';
        }
        h += "};\ninline const uint8_t* starterVrs(size_t& n) { n = sizeof kStarterVrs; return kStarterVrs; }\n}\n";
        std::ofstream o(argv[3], std::ios::binary); o << h;
        if (!o) { std::fprintf(stderr, "cannot write %s\n", argv[3]); return 1; }
        std::printf("starter: %zu bytes (%zu airlines, %zu model types, %zu blocks)\n", v.bytes.size(), v.airlines, v.types, v.blocks);
        return 0;
    }
    if (cmd == "lookup" && argc >= 4) {
        Db& db = Db::get();
        db.setDir(argv[2]);
        db.refresh(true);
        Info i;
        const uint32_t hex = uint32_t(std::strtoul(argv[3], nullptr, 16));
        db.lookupHex(hex, i);
        if (argc >= 5) db.lookupCallsign(argv[4], i.r, hex, i);
        if (argc >= 7) Db::judge(i, std::atof(argv[5]), std::atof(argv[6]));
        std::printf("%s\n", i.json().c_str());
        return 0;
    }
    std::fprintf(stderr, "usage: see the head of adsb-data-tool.cpp\n");
    return 2;
}
