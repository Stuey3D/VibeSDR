int main() {
    printf("test-dab-mp2\n");

    // ── the derived quantisation constants ──────────────────────────────────
    // ★★ ISO tabulates C and D per level count; both are derivable, and the property that makes
    //    them so is worth asserting directly: the MIDDLE code must dequantise to exactly zero.
    for (int nl : { 3, 5, 7, 9, 15, 31, 63, 127, 255, 511, 1023, 2047, 4095, 8191, 16383, 32767, 65535 }) {
        char m[64];
        snprintf(m, sizeof m, "nlevels %d: the middle code is silence", nl);
        CHECK(std::fabs(dequant((nl - 1) / 2, nl)) < 1e-6f, m);
        snprintf(m, sizeof m, "nlevels %d: the extremes are symmetric", nl);
        CHECK(std::fabs(dequant(0, nl) + dequant(nl - 1, nl)) < 1e-5f, m);
    }
    CHECK(quantBits(3) == 2 && quantBits(7) == 3 && quantBits(65535) == 16, "bits per sample");
    CHECK(quantCodeBits(3) == 5 && quantCodeBits(5) == 7 && quantCodeBits(9) == 10,
          "grouped codewords are 5, 7 and 10 bits");
    CHECK(quantGrouped(3) && quantGrouped(5) && quantGrouped(9) && !quantGrouped(7),
          "only 3, 5 and 9 are grouped");

    // ── scalefactors ────────────────────────────────────────────────────────
    CHECK(std::fabs(scaleFactor(0) - 2.0f) < 1e-6f, "scalefactor 0 is 2.0");
    CHECK(std::fabs(scaleFactor(3) - 1.0f) < 1e-6f, "every third step halves it");
    CHECK(std::fabs(scaleFactor(6) - 0.5f) < 1e-6f, "and again");

    // ── the measured synthesis window ───────────────────────────────────────
    {
        float peak = 0; for (float v : kSynthWindow) peak = std::fabs(v) > peak ? std::fabs(v) : peak;
        // ★ Two values that confirm the MEASURED table against the published ISO one.
        CHECK(std::fabs(peak - 1.144989f) < 1e-5f, "window peak is 1.144989, as ISO tabulates");
        CHECK(std::fabs(kSynthWindow[1] + 0.000015259f) < 1e-8f, "D[1] = -0.000015259");
        CHECK(kSynthWindow[0] == 0.0f, "D[0] = 0");
        // ★★ The symmetry the eight unmeasurable coefficients were filled from — asserted over the
        //    whole table, so a bad fill cannot hide.
        int bad = 0;
        for (int i = 1; i < 256; ++i) {
            const float want = ((i & 63) == 0) ? kSynthWindow[i] : -kSynthWindow[i];
            if (std::fabs(want - kSynthWindow[512 - i]) > 2e-6f) ++bad;
        }
        CHECK(bad == 0, "D[512-i] = -D[i], or +D[i] on multiples of 64");
    }

    // ── the allocation tables, against the spec's own stated sums ───────────
    {
        int s27 = 0, s8 = 0;
        for (int sb = 0; sb < 32; ++sb) { s27 += kAllocTable48Wide.sb[sb].nbal; s8 += kAllocTable48Narrow.sb[sb].nbal; }
        // TS 103 466: "If sblimit is equal to 27, the sum of nbal is equal to 88 … equal to 26".
        CHECK(s27 == 88, "table 4: sum of nbal is 88, as the spec states");
        CHECK(s8 == 26, "table 5: sum of nbal is 26, as the spec states");
        CHECK(kAllocTable48Wide.sblimit == 27 && kAllocTable48Narrow.sblimit == 8, "sblimits");
        CHECK(kAllocTable24.sblimit == 30, "the 24 kHz table reaches 30 sub-bands");
    }

    // ── ★★★ DECODE A REAL FILE ──────────────────────────────────────────────
    {
        Mp2Info h = mp2Header(kTone, sizeof kTone);
        CHECK(h.valid, "the embedded frame is a valid Layer II header");
        CHECK(h.sampleRateHz == 48000 && h.channels == 1 && h.bitrateKbps == 64, "48 kHz mono 64 kbit/s");
        CHECK(h.frameBytes == 192, "144 x 64000 / 48000 = 192 bytes");

        Mp2Decoder dec;
        std::vector<float> out, all;
        size_t off = 0; int frames = 0;
        while (off + 4 <= sizeof kTone) {
            Mp2Info f = mp2Header(kTone + off, sizeof kTone - off);
            if (!f.valid || off + size_t(f.frameBytes) > sizeof kTone) break;
            if (dec.decode(kTone + off, sizeof kTone - off, out) <= 0) break;
            all.insert(all.end(), out.begin(), out.end());
            off += size_t(f.frameBytes); ++frames;
        }
        CHECK(frames == 7, "seven frames decoded");
        CHECK(all.size() == size_t(frames) * 1152, "1152 samples per frame");

        // ★ It must be a 1 kHz TONE, not merely non-zero. Correlate against 1 kHz and against a
        //   neighbour that should be absent — a decoder producing noise passes an energy test and
        //   fails this one.
        double e1 = 0, q1 = 0, e3 = 0, q3 = 0, energy = 0;
        const size_t skip = 1152;                     // the filterbank needs to fill
        for (size_t i = skip; i < all.size(); ++i) {
            const double t = double(i) / 48000.0, v = all[i];
            e1 += v * std::cos(2 * M_PI * 1000 * t); q1 += v * std::sin(2 * M_PI * 1000 * t);
            e3 += v * std::cos(2 * M_PI * 3000 * t); q3 += v * std::sin(2 * M_PI * 3000 * t);
            energy += v * v;
        }
        const double at1k = std::sqrt(e1 * e1 + q1 * q1), at3k = std::sqrt(e3 * e3 + q3 * q3);
        CHECK(energy > 1.0, "the decode produced real audio");
        char m[96]; snprintf(m, sizeof m, "1 kHz dominates 3 kHz by %.0fx", at1k / (at3k + 1e-9));
        CHECK(at1k > at3k * 50, m);
    }

    if (fails == 0) printf("  all passed\n");
    else            printf("  %d FAILED\n", fails);
    return fails ? 1 : 0;
}
